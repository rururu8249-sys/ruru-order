-- ============================================================
-- 3단계 — 자동 갱신(매시 정각 cron)을 위한 준비  (2026-09-20)
--
-- 왜 필요한가
--   SQL 편집기에서 직접 돌릴 때는 시간 제한이 넉넉하지만,
--   서버(cron)에서 API로 호출할 때는 짧은 제한이 걸려 «집계 도중 끊김»이 날 수 있다.
--   이 함수에 한해 제한을 180초로 늘려 둔다.
--
-- 안전: 함수의 «실행 시간 제한»만 바꾼다. 계산 내용·데이터 변경 0.
-- ============================================================

alter function refresh_product_sales_stats() set statement_timeout = '180s';

-- 확인 — 지금 한 번 돌려본다(결과가 나오면 정상)
select * from refresh_product_sales_stats();
