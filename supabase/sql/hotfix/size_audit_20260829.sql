db as (
  select
    p.id                                              as product_id,
    p.product_name                                    as brand,
    d.key                                             as detail_name,
    -- "BB(버버리)-405M 남성용 패딩 아우터 · 베이지"  ->  "BB-405M"
    split_part(trim(regexp_replace(d.key, '\(.*?\)', '', 'g')), ' ', 1) as code,
    coalesce((
      select string_agg(s, ',' order by ord)
      from jsonb_array_elements_text(d.value->'sizes') with ordinality t(s, ord)
      where nullif(trim(s), '') is not null and trim(s) <> '없음'
    ), '')                                            as db_sizes
  from public.products p
  cross join lateral jsonb_each((p.product_note::jsonb)->'brand_group'->'detail_options') d
  where p.product_note is not null
    and p.product_note <> ''
    and jsonb_typeof((p.product_note::jsonb)->'brand_group'->'detail_options') = 'object'
)
select
  db.code                                             as 코드,
  excel.excel_sizes                                   as 엑셀_사이즈,
  db.db_sizes                                         as 등록된_사이즈,
  case
    when excel.code is null                    then '엑셀에 없는 코드'
    when db.db_sizes = ''                      then '등록 사이즈 비어있음'
    when db.db_sizes = excel.excel_sizes       then '같음'
    else '다름'
  end                                                 as 판정,
  db.brand                                            as 브랜드,
  db.detail_name                                      as 등록된_세부상품명,
  db.product_id                                       as 상품ID
from db
left join excel on excel.code = db.code
where excel.code is null
   or db.db_sizes <> excel.excel_sizes
order by 판정, db.code;
