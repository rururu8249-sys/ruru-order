-- ④ 해외방송 — 날짜(9/2, 9/9)를 지우고 «방송일 기준»으로 바꿈
--    → 방송마다 공지를 다시 고칠 필요가 없어짐
-- ============================================================
update notices set
  title = '✈️ 해외방송 주문 · 배송 안내',
  content = '해외방송 상품은 주문 접수 후 해외 업체로 개별 주문·제작이 들어가는 상품입니다.
제작이 시작된 뒤에는 일반 재고상품처럼 중간 취소가 어려우니 주문 전 신중히 결정해 주세요.

✅ 배송기간
해외방송 주문건은 해당 방송일 기준 약 2~3주 정도 걸립니다.
(개별 주문일이 아니라 방송일 기준입니다)

배송이 시작되면 송장번호를 순차적으로 안내해 드립니다.
안내드린 기간 안에는 제작·배송이 정상 진행 중이니
조금만 여유 있게 기다려주시면 감사하겠습니다 🙏',
  is_pinned = true,
  sort_order = 3
where title = '해외배송 상품';

-- ============================================================
-- ⑤ 교환·반품 — 흩어진 3개(교환·환불 기준 / 반품 동일성 / 구매 전 동의)를 하나로
--    반품비 금액은 기존 문구 그대로 유지 (국내 10,000 / 해외 20,000)
-- ============================================================
update notices set
  title = '🔄 교환 · 반품 안내',
  content = '✅ 교환·환불이 가능한 경우
• 중대한 하자
• 오배송
• 표시·광고 내용과 다른 경우
