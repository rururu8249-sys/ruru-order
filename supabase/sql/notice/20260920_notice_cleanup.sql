• 세탁 / 착용 / 사용 흔적
• 향수·섬유탈취제·체취 등 냄새
• 구성품 누락 또는 다른 상품 반송
• 포장 훼손 및 상품 가치 저하
※ 의류·신발·악세사리 특성상 사용 시 재판매가 어려울 수 있습니다.

