혹시 이름을 다르게 넣으셨거나 금액이 다르면 방송 채팅 또는 쪽지로 알려주세요.
바로 찾아서 처리해 드립니다 🙏',
  '공지', true, true, 1
where not exists (select 1 from notices where title = '💰 입금 안내 (무통장입금)');

-- ============================================================
-- ③ 배송 공지 — 기존 「📦 배송 및 송장 안내」 정리 + 합배송 안내 흡수
--    (별표 *…* 가 화면에 그대로 보이던 것도 제거)
-- ============================================================
update notices set
