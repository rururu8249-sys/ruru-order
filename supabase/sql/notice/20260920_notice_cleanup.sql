  content = '평균 출고는 평일 영업일 기준 2~3일 정도 걸립니다.

📮 송장번호
출고 당일 루루동이 밴드에서 확인하실 수 있습니다.
택배 출고 시 택배사에서 고객님 휴대폰으로 배송 안내 문자가 자동 발송됩니다.

📌 송장 문의 전에 휴대폰 문자함과 스팸함을 먼저 확인해 주세요 🙏

📦 합배송(묶음배송)
