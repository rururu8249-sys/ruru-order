-- ============================================================
-- ⑥ 병행수입 / 개인정보 — 내용은 법적 고지라 그대로, 순서만 정리
-- ============================================================
update notices set is_pinned = false, sort_order = 5
where title = '병행수입 / B-grade / backdoor 판매상품 안내';

update notices set is_pinned = false, sort_order = 6
where title = '개인정보 수집·이용 안내';

commit;

-- ============================================================
-- ⑦ 결과 확인 (고객이 보게 될 순서 그대로)
-- ============================================================
select sort_order, is_pinned, category, title
from notices
where is_visible = true
order by is_pinned desc, sort_order asc, created_at desc;
