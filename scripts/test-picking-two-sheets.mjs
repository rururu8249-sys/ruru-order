import assert from 'node:assert/strict';
import ExcelJS from 'exceljs';
import {createUiLoader} from './admin-ui-test-loader.mjs';
let blob;
globalThis.window={URL:{createObjectURL(value){blob=value;return 'blob:test';},revokeObjectURL(){}}};
globalThis.document={createElement(){return {click(){},remove(){}};},body:{appendChild(){}}};
const {exportLiveOrdersForPicking}=createUiLoader({exceljs:{default:ExcelJS},'@/lib/adminToast':{showAdminToast(){}}})('components/admin-live/adminLiveOrderExcelExport.ts');
const base={nickname:'검수고객',paymentStatus:'paid',createdAt:'2026-10-03T01:00:00Z',paidAtFull:'2026-10-03T01:00:00Z'};
const ordinary={...base,id:'1',items:[{id:'1',productName:'일반상품',size:'M',qty:2,amount:20000}]};
const repick={...base,id:'2',items:[{id:'2',productName:'BB-58',size:'XL',qty:1,amount:195000,repickRequiredAt:'2026-10-04T01:00:00Z',repickBefore:{product_name:'BB-60',size:'L',qty:2}}]};
const late={...base,id:'3',paidAtFull:'2026-10-04T01:00:00Z',items:[{id:'3',productName:'추가상품',size:'38',qty:1,amount:135000}]};
async function run(orders,meta={}){
 await exportLiveOrdersForPicking(orders,{filterLabel:'전체보기',...meta});
 const workbook=new ExcelJS.Workbook();await workbook.xlsx.load(await blob.arrayBuffer());return workbook;
}
const workbook=await run([ordinary,repick,late]);
assert.deepEqual(workbook.worksheets.map(s=>s.name),['물건챙기기','변경 및 추가','고객이슈·특이사항']);
const main=workbook.getWorksheet('물건챙기기');
const additional=workbook.getWorksheet('변경 및 추가');
assert.equal(main.rowCount,2,'only ordinary work belongs in the main sheet');
assert.equal(main.getCell('C2').value,'일반상품');
assert.equal(main.getCell('E2').value,2);
assert.equal(main.getCell('F2').value,20000);
assert.equal(main.getCell('F2').numFmt,'#,##0');
assert.equal(additional.rowCount,3,'changed and additional work appear exactly once');
assert.match(additional.getCell('E2').value,/BB-60.*L.*2개/);
assert.match(additional.getCell('F2').value,/BB-58.*XL.*1개/);
assert.equal(additional.getCell('G3').value,'결제 후 추가 챙기기');
assert.match(additional.getCell('F3').value,/추가상품.*38.*1개/);
assert.equal(main.autoFilter,'A1:H2');
assert.equal(additional.autoFilter,'A1:G3');
assert(main.getColumn(5).width<=8);
const onlyAttention=await run([repick,late]);
assert.equal(onlyAttention.getWorksheet('물건챙기기').rowCount,1,'empty ordinary sheet keeps a header');
assert.equal(onlyAttention.getWorksheet('변경 및 추가').rowCount,3);
const visible=await run([ordinary,repick,late],{visibleItemIds:['1','3']});
assert.equal(visible.getWorksheet('물건챙기기').rowCount,2);
assert.equal(visible.getWorksheet('변경 및 추가').rowCount,2,'excluded items do not leak into attention sheet');
const active=await run([{...ordinary,paymentStatus:'card_paid',paidAtFull:null}],{attentionItemIds:[]});
assert.equal(active.getWorksheet('물건챙기기').rowCount,2);
assert.equal(active.getWorksheet('변경 및 추가').rowCount,1,'selected-broadcast card payments stay in ordinary work');
const issues=[{date:'2026. 10. 05.',customer:'검수',product:'취소상품 · L · 1개',action:'환불',status:'미처리',memo:'출고 제외'}];
const issueOnly=await run([],{exceptions:issues});
assert.equal(issueOnly.getWorksheet('물건챙기기').rowCount,1);
assert.equal(issueOnly.getWorksheet('변경 및 추가').rowCount,1);
assert.equal(issueOnly.getWorksheet('고객이슈·특이사항').getCell('D2').value,issues[0].product);
assert.equal(issueOnly.getWorksheet('고객이슈·특이사항').getCell('C1').value,'방송');
for(const sheet of issueOnly.worksheets) assert(!sheet.getRow(1).values.includes('주문번호'));
assert.equal(additional.getCell('F1').value,'변경 후');
const canceled=await run([],{cancellations:[{customer:'취소고객',broadcast:'의류',orderedAt:'2026. 10. 03. 10:00',attentionAt:'',before:'상의 · L · 1개',current:'주문 취소',kind:'주문 취소 · 출고 제외'}]});
assert.equal(canceled.getWorksheet('변경 및 추가').getCell('D2').value,'취소: 기록 없음');
assert.equal(canceled.getWorksheet('변경 및 추가').getCell('G2').value,'주문 취소 · 출고 제외');
console.log('PASS real XLSX roundtrip: three disjoint sheets, issue-only export, simplified headers and unchanged amounts');
