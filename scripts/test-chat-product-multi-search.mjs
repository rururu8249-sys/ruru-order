import assert from 'node:assert/strict';
import {createUiLoader} from './admin-ui-test-loader.mjs';
const C=createUiLoader()('lib/liveChatProductCommand.ts');
const item=(id,name)=>({productId:String(id),detailName:'',texts:[name],line:name,soldOut:false,sizes:[]});
const items=[item(1,'PD-509 블랙'),item(2,'BB-307 베이지'),item(3,'MC-333 핑크'),item(4,'PD-333 블랙'),item(5,'PD-5090 화이트')];
assert.equal(typeof C.searchChatProductGroups,'function','comma search must be implemented');
let groups=C.searchChatProductGroups('프509, 버307',items);
assert.deepEqual(groups.map(g=>g.items.map(p=>p.productId)),[['1'],['2']]);
assert.deepEqual(C.searchChatProductGroups('333',items)[0].items.map(p=>p.productId),['3','4']);
assert.equal(C.searchChatProductGroups('몽',items)[0].items[0].productId,'3');
assert.equal(C.searchChatProductGroups('프509, 없음',items)[1].items.length,0);
assert.deepEqual(C.parseChatProductQueries('/프509, 버307'),['프509','버307']);
assert.equal(C.parseChatProductQueries('/프509, '),null);
assert.equal(C.parseChatProductQueries('/몽'),null);
assert.equal(C.parseChatProductSelection({targets:[],mode:'replace'}),null);
assert.equal(C.parseChatProductSelection({targets:[{productId:'1'},{}],mode:'replace'}),null);
assert.equal(C.parseChatProductSelection({targets:[{productId:'1'}],mode:'oops'}),null);
assert.deepEqual(C.parseChatProductSelection({targets:[{productId:'1'},{productId:'1'}],mode:'append'}),{targets:[{productId:'1',detailName:''}],mode:'append'});
console.log('PASS multi search: separate terms, exact numbers, ambiguity, unknown terms, strict selection');
