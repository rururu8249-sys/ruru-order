import assert from "node:assert/strict";
import { shippingAddressKey } from "../lib/shippingAddressKey.ts";

const same = (a, b, why) => assert.equal(shippingAddressKey(...a), shippingAddressKey(...b), why);
const diff = (a, b, why) => assert.notEqual(shippingAddressKey(...a), shippingAddressKey(...b), why);

// ── 실제 사고 (2026-09-22 아지라엘 님) — 「도」 한 글자 차이 ──
same(
  ["경기 화성시 동탄구 동탄순환대로21길 15", "1347-1401"],
  ["경기도 화성시 동탄구 동탄순환대로21길 15", "1347-1401"],
  "경기 = 경기도",
);
// ── 같은 날 정상 합배송된 슈니 님 (원래도 같았음 — 회귀 방지) ──
same(
  ["전남광주통합특별시 여수시 박람회길 61 (덕충동, 엑스포힐스테이트1단지)", "113동501호"],
  ["전남광주통합특별시 여수시 박람회길 61 (덕충동, 엑스포힐스테이트1단지)", "113동501호"],
  "글자까지 같은 주소",
);

// ── 시도 표기 흔한 변형 ──
same(["서울특별시 중구 세종대로 110", "5층"], ["서울 중구 세종대로 110", "5층"], "서울특별시 = 서울");
same(["전라남도 여수시 박람회길 61", "101동"], ["전남 여수시 박람회길 61", "101동"], "전라남도 = 전남");
same(["제주특별자치도 제주시 첨단로 242", "2동"], ["제주 제주시 첨단로 242", "2동"], "제주특별자치도 = 제주");
same(["강원특별자치도 춘천시 중앙로 1", "3호"], ["강원도 춘천시 중앙로 1", "3호"], "강원특별자치도 = 강원도");

// ── 띄어쓰기·괄호 차이 ──
same(["경기 화성시 동탄순환대로21길 15", "1347-1401"], ["경기 화성시 동탄순환대로21길15", "1347-1401"], "띄어쓰기");
same(["경기 화성시 A로 1 (반송동, 시범단지)", "101동"], ["경기 화성시 A로 1", "101동"], "괄호 안은 무시");
same(["경기 화성시 A로 1", " 101동 "], ["경기 화성시 A로 1", "101동"], "앞뒤 공백");

// ── ★ 달라야 하는 것 (다른 주소가 같아지면 배송비를 부당하게 0원 처리하게 된다) ──
diff(["경기 화성시 A로 1", "101동"], ["경기 화성시 A로 1", "102동"], "상세주소가 다르면 다른 집");
diff(["경기 화성시 A로 1", "101동"], ["경기 수원시 A로 1", "101동"], "시가 다르면 다른 곳");
diff(["경기 광주시 오포읍 A로 1", "101동"], ["광주 북구 A로 1", "101동"], "경기 광주시 ≠ 광주광역시");
diff(["경기 화성시 A로 11", "1동"], ["경기 화성시 A로 1", "11동"], "숫자 자리가 다르면 다른 곳");

// ── 주소를 모르면 빈 값 → 합배송 성립 금지 ──
assert.equal(shippingAddressKey("", ""), "");
assert.equal(shippingAddressKey(null, undefined), "");
assert.equal(shippingAddressKey("   ", "  "), "");
// 상세주소만 있어도 키는 생긴다(주소 없이 상세만 있는 옛 데이터)
assert.ok(shippingAddressKey("", "101동").length > 0);

// ── 길 이름 한가운데의 시도 이름은 건드리지 않는다 ──
diff(["경기 화성시 경기도로 1", "1동"], ["경기 화성시 경기로 1", "1동"], "가운데 「경기도로」는 길 이름");

console.log("✅ shipping address key OK");
