import assert from 'node:assert/strict';
import React from 'react';
import TestRenderer,{act} from 'react-test-renderer';
import {createUiLoader} from './admin-ui-test-loader.mjs';
globalThis.IS_REACT_ACT_ENVIRONMENT=true;
let writes=0,closed=0,moved=0,conflict=false,lastBody;
const source={id:2,product_name:'임시',price:39000,stock:7,image_url:'actual.jpg',size_options:['S','M'],product_description:'원본 설명'};
const parent={id:1,product_name:'브랜드',product_note:'{"brand_group":{"enabled":true}}'};
globalThis.fetch=async(_url,options)=>{if(options?.method==='POST'){writes++;lastBody=JSON.parse(options.body);return {ok:!conflict,status:conflict?409:200,json:async()=>conflict?{error:'상품 상태가 변경되었습니다.'}:{link:{sourceId:'2'},replayed:false}};}return {ok:true,status:200,json:async()=>({source,parent,sourceVersion:'a'.repeat(32),parentVersion:'b'.repeat(32)})};};
const {default:Dialog}=createUiLoader({})('components/admin-live/ProductBrandMoveDialog.tsx');
let renderer;
await act(async()=>{renderer=TestRenderer.create(React.createElement(Dialog,{source,brands:[parent],onClose:()=>closed++,onMoved:()=>moved++}));});
const button=label=>renderer.root.findAllByType('button').find(node=>node.children.join('')===label);
assert.equal(button('이 브랜드로 이동').props.disabled,true);
await act(async()=>button('취소').props.onClick());
assert.equal(writes,0);assert.equal(closed,1);
await act(async()=>renderer.root.findByProps({'aria-label':'이동할 브랜드'}).props.onChange({target:{value:'1'}}));
await act(async()=>renderer.root.findByProps({'aria-label':'이동 후 상품명'}).props.onChange({target:{value:'NEW'}}));
assert.equal(button('이 브랜드로 이동').props.disabled,false);
assert.ok(JSON.stringify(renderer.toJSON()).includes('actual.jpg'));
assert.ok(JSON.stringify(renderer.toJSON()).includes('39,000'));
await act(async()=>button('이 브랜드로 이동').props.onClick());
assert.equal(writes,1);assert.equal(moved,1);
await act(async()=>renderer.unmount());
conflict=false;
await act(async()=>{renderer=TestRenderer.create(React.createElement(Dialog,{source,brands:[parent],undoParentId:'1',onClose:()=>closed++,onMoved:()=>moved++}));});
const beforeUndo=writes;
await act(async()=>{const save=button('독립 상품으로 되돌리기').props.onClick;await Promise.all([save(),save()]);});
assert.equal(writes,beforeUndo+1,'same-frame repeated click cannot submit twice');
assert.equal(lastBody.action,'undo');assert.equal(lastBody.sourceId,'2');assert.equal(lastBody.parentId,'1');
assert.equal(lastBody.expectedSourceVersion,'a'.repeat(32));
await act(async()=>renderer.unmount());
conflict=true;
const beforeConflict=moved;
await act(async()=>{renderer=TestRenderer.create(React.createElement(Dialog,{source,brands:[parent],onClose:()=>closed++,onMoved:()=>moved++}));});
await act(async()=>renderer.root.findByProps({'aria-label':'이동할 브랜드'}).props.onChange({target:{value:'1'}}));
await act(async()=>renderer.root.findByProps({'aria-label':'이동 후 상품명'}).props.onChange({target:{value:'충돌 후 유지'}}));
await act(async()=>button('이 브랜드로 이동').props.onClick());
assert.equal(renderer.root.findByProps({'aria-label':'이동 후 상품명'}).props.value,'충돌 후 유지');
assert.equal(button('이 브랜드로 이동').props.disabled,true,'conflict requires fresh review, not blind retry');
assert.equal(moved,beforeConflict);
await act(async()=>button('최신 상태 다시 확인').props.onClick());
assert.equal(button('이 브랜드로 이동').props.disabled,false);
await act(async()=>renderer.unmount());
console.log('PASS move dialog explicit selection, original preview, cancel and exact authenticated save');
