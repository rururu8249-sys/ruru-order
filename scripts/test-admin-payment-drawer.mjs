import assert from 'node:assert/strict';
import React from 'react';
import Renderer,{act} from 'react-test-renderer';
import {createUiLoader} from './admin-ui-test-loader.mjs';
globalThis.IS_REACT_ACT_ENVIRONMENT=true;
globalThis.window={setTimeout,clearTimeout};
class FocusNode {isConnected=true;focus(){document.activeElement=this;}}
globalThis.HTMLElement=FocusNode;
globalThis.document={activeElement:null};
const requests=[];
globalThis.fetch=(url)=>new Promise(resolve=>requests.push({url,resolve}));
const load=createUiLoader();
const Panel=load('components/admin-live/payment-ledger/PaymentMatchPanel.tsx').default;
const Filters=load('components/admin-live/payment-ledger/DepositLedgerFilters.tsx').default;
const Table=load('components/admin-live/payment-ledger/DepositLedgerTable.tsx').default;
const Detail=load('components/admin-live/payment-ledger/DepositDetailModal.tsx').default;
const row=(id,name)=>({id,depositor_name:name,amount:12000,deposited_at:new Date().toISOString(),status:'unmatched'});
const a=row('a','기존입금'); const b=row('b','최신입금');
const respond=async (request, rows, ok=true)=>act(async()=>request.resolve({ok,json:async()=>({ok,deposits:rows,message:ok?'':'조회실패'})}));
let tree;
await act(async()=>{tree=Renderer.create(React.createElement(Panel,{deposits:[a],presentation:'drawer'}));});
assert.equal(tree.root.findByType(Table).props.rows[0].id,'a','parent rows immediately visible');
const f=()=>tree.root.findByType(Filters);
await act(async()=>f().props.onFromDateChange('2026-01-01'));
await act(async()=>f().props.onApplyDate());
await respond(requests[1],[b]);
await respond(requests[0],[a]);
assert.equal(tree.root.findByType(Table).props.rows[0].id,'b','late initial response must not overwrite newer date query');
await act(async()=>f().props.onKeywordChange('최신'));
await act(async()=>{await new Promise(resolve=>setTimeout(resolve,370));});
await act(async()=>tree.root.findByType(Table).props.onOpenDetail(b));
assert.equal(tree.root.findByType(Detail).props.presentation,'inline','drawer details do not open a second modal');
await act(async()=>tree.root.findByType(Detail).props.onClose());
assert.equal(f().props.keyword,'최신');
assert.equal(f().props.fromDate,'2026-01-01');
await act(async()=>f().props.onApplyDate());
await respond(requests[2],[],false);
assert.equal(tree.root.findByType(Table).props.rows[0].id,'b','failed refresh retains confirmed rows');
assert.ok(JSON.stringify(tree.toJSON()).includes('조회실패'));
await act(async()=>tree.unmount());
requests.length=0;
await act(async()=>{tree=Renderer.create(React.createElement(Panel,{deposits:[],presentation:'drawer'}));});
await respond(requests[0],[],false);
assert.equal(tree.root.findAllByType(Table).length,0,'initial error not normal empty list');
await act(async()=>tree.unmount());
console.log('PASS deposit race, failure, inline detail and preserved filters');

requests.length=0;
await act(async()=>{tree=Renderer.create(React.createElement(Panel,{deposits:[a],presentation:'drawer'}));});
await respond(requests[0],[a]);
await act(async()=>{void tree.root.findAllByType('button').find(n=>n.children.join('')==='입금내역 새로고침').props.onClick();});
const sync=requests[1];
await act(async()=>f().props.onFromDateChange('2026-01-01'));
await act(async()=>f().props.onApplyDate());
const periodUrl=requests[2].url;
const older={...row('old','과거입금'),deposited_at:'2026-01-02T12:00:00Z'};
await respond(requests[2],[older,a]);
await respond(sync,[]);
assert.equal(requests[3].url,periodUrl,'sync completion must query latest applied period, not captured initial period');
await respond(requests[3],[older,a]);
assert.equal(tree.root.findByType(Table).props.rows.length,2);
await act(async()=>tree.unmount());
console.log('PASS delayed Bankda sync respects period changed while pending');

const rowButton=new FocusNode(), backButton=new FocusNode();
const scroller={scrollTop:640};
const ledgerNode={closest:()=>scroller,querySelector:()=>backButton,contains:node=>node===rowButton};
globalThis.document={activeElement:rowButton};
requests.length=0;
await act(async()=>{tree=Renderer.create(React.createElement(Panel,{deposits:[a],presentation:'drawer'}),{createNodeMock:()=>ledgerNode});});
await act(async()=>tree.root.findByType(Table).props.onOpenDetail(a));
assert.equal(document.activeElement,backButton,'inline detail focuses its back control, not hidden row');
assert.equal(scroller.scrollTop,0,'detail begins at top');
scroller.scrollTop=12;
await act(async()=>tree.root.findByType(Detail).props.onClose());
assert.equal(document.activeElement,rowButton,'back restores focused deposit row');
assert.equal(scroller.scrollTop,640,'back restores list scroll even when detail was shorter');
await act(async()=>tree.unmount());
console.log('PASS inline detail list scroll and row-focus restoration');
