import assert from 'node:assert/strict';
import React from 'react';
import TestRenderer,{act} from 'react-test-renderer';
import {createUiLoader} from './admin-ui-test-loader.mjs';
globalThis.IS_REACT_ACT_ENVIRONMENT=true;
const {default:Field}=createUiLoader()('components/customer/CustomerManualField.tsx');
let value='';
let renderer;
await act(async()=>{renderer=TestRenderer.create(React.createElement(Field,{id:'options',label:'상품번호 · 옵션(색상·사이즈)',value:'',onChange:next=>{value=next;},placeholder:'예: BB-60 / 베이지 / M',help:'방송에서 확인한 내용을 입력해 주세요.'}));});
assert.equal(renderer.root.findByType('label').props.htmlFor,'options');
assert.equal(renderer.root.findByType('input').props.id,'options');
assert.equal(renderer.root.findByType('input').props['aria-invalid'],false,'empty untouched field must not appear invalid');
assert.equal(renderer.root.findAllByProps({role:'alert'}).length,0);
await act(async()=>renderer.root.findByType('input').props.onChange({target:{value:'BB-60 / 베이지 / M'}}));
assert.equal(value,'BB-60 / 베이지 / M','typed options must reach order state unchanged');
await act(async()=>renderer.update(React.createElement(Field,{id:'amount',label:'상품 1개 금액',value:'',onChange:()=>{},placeholder:'예: 59,000',help:'방송에서 안내한 가격',numeric:true,error:'금액을 입력해 주세요.'})));
assert.equal(renderer.root.findByType('input').props.inputMode,'numeric');
assert.equal(renderer.root.findByType('input').props['aria-invalid'],true);
assert.equal(renderer.root.findByProps({role:'alert'}).children.join(''),'금액을 입력해 주세요.');
await act(async()=>renderer.unmount());
console.log('PASS accessible manual fields, unchanged input, errors only on attempted validation');
