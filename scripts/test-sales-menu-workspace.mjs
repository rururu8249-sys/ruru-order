import assert from 'node:assert/strict';
import React from 'react';
import Renderer,{act} from 'react-test-renderer';
import {createUiLoader} from './admin-ui-test-loader.mjs';
globalThis.IS_REACT_ACT_ENVIRONMENT=true;
globalThis.window={addEventListener(){},removeEventListener(){}};
globalThis.document={querySelector(){return null;}};
const query=new Proxy({}, {get:(_,key)=>key==='then'?((resolve)=>Promise.resolve({data:[],error:null}).then(resolve)):(()=>query)});
const load=createUiLoader({'./WidgetProductLibraryPanel.module.css':{default:{}},'@/lib/supabase':{supabase:{from:()=>query}},'@/lib/adminToast':{showAdminToast(){}},'./ExcelBulkImportPopup':{default:()=>null}});
const Panel=load('components/admin-live/AdminLiveProductManagePopup.tsx').default;
const labels=tree=>tree.root.findAllByType('button').map(button=>button.children.filter(child=>typeof child==='string').join(''));
let tree;
await act(async()=>{tree=Renderer.create(React.createElement(Panel,{embedded:true,salesOnly:true,onClose(){}}));});
assert.ok(JSON.stringify(tree.toJSON()).includes('판매 있는 방송'),'sales destination must render sales summary');
assert.equal(labels(tree).some(label=>label.includes('상품 등록')||label.includes('엑셀 대량등록')),false,'read-only sales view must not expose catalog actions');
assert.equal(labels(tree).includes('방송 상품'),false,'sales destination must not expose nested catalog navigation');
await act(async()=>tree.unmount());
await act(async()=>{tree=Renderer.create(React.createElement(Panel,{embedded:true,initialTab:'history',onClose(){}}));});
assert.equal(labels(tree).includes('판매 기록'),false,'catalog navigation must not retain moved sales tab');
assert.ok(labels(tree).includes('방송 상품'),'stale history tab must fall back to catalog workspace');
await act(async()=>tree.unmount());
console.log('PASS sales-only workspace and stale catalog-tab fallback');
