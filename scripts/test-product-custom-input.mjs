import assert from 'node:assert/strict';
import React from 'react';
import TestRenderer, {act} from 'react-test-renderer';
import {createUiLoader} from './admin-ui-test-loader.mjs';
globalThis.IS_REACT_ACT_ENVIRONMENT = true;
globalThis.window = {innerWidth:1200,addEventListener(){},removeEventListener(){},dispatchEvent(){}};
globalThis.document = {addEventListener(){},removeEventListener(){}};
let saved;
const {default:Form} = createUiLoader({'@/lib/supabase':{supabase:{}},'@/lib/adminCatalogWrite':{adminCatalogWrite:async payload=>{saved=payload;return {data:{id:9002},error:null};}},'@/lib/adminToast':{showAdminToast(){}},'@/lib/adminConfirm':{showAdminConfirm:async()=>true}})('components/admin-live/quick-product/QuickProductFastForm.tsx');
const label = '상품번호 · 옵션(색상·사이즈)';
const product = {id:9002,__catalog_edit_version:'a'.repeat(32),product_name:'특가상품',price:0,stock:0,color_options:[],size_options:['없음'],product_note:JSON.stringify({stock_management_enabled:false,custom_input_label:label})};
let renderer;
await act(async()=>{renderer=TestRenderer.create(React.createElement(Form,{activeBroadcastId:null,initialProduct:product}));});
const text=node=>node.children.map(child=>typeof child==='string'?child:typeof child==='object'?text(child):'').join('');
const buttons=()=>renderer.root.findAllByType('button');
const expand=buttons().find(button=>text(button).includes('자세히 열기'));
if(expand) await act(async()=>expand.props.onClick());
const toggle=()=>renderer.root.findByProps({'aria-label':'고객 직접입력 사용'});
assert.equal(toggle().props.checked,true,'legacy custom field must reopen as a separate enabled setting');
assert.equal(renderer.root.findByProps({'aria-label':'직접입력 칸 제목'}).props.value,label);
assert.equal(renderer.root.findByProps({'aria-label':'색상 사용 안 함'}).props['aria-pressed'],true,'unified custom input must not be presented as color entry');
await act(async()=>buttons().find(button=>text(button)==='저장').props.onClick());
assert.equal(JSON.parse(saved.values.product_note).custom_input_label,label);
assert.deepEqual(Array.from(saved.values.color_options),[],'saving presentation correction cannot change legacy option keys');
await act(async()=>toggle().props.onChange({target:{checked:false}}));
await act(async()=>buttons().find(button=>text(button)==='저장').props.onClick());
assert.equal(JSON.parse(saved.values.product_note).custom_input_label,undefined);
assert.deepEqual(Array.from(saved.values.color_options),['없음'],'turning off unified entry cannot reveal an unintended color input');
await act(async()=>toggle().props.onChange({target:{checked:true}}));
await act(async()=>renderer.root.findByProps({'aria-label':'직접입력 칸 제목'}).props.onChange({target:{value:''}}));
await act(async()=>buttons().find(button=>text(button)==='저장').props.onClick());
assert.equal(JSON.parse(saved.values.product_note).custom_input_label,label,'enabled entry with empty title must retain a usable default');
await act(async()=>renderer.unmount());
console.log('PASS independent customer input setting, legacy keys, and explicit disable');
const comboProduct={...product,product_name:'기존 세부상품',product_note:JSON.stringify({stock_management_enabled:false,custom_input_label:label,combo_mode:true,option_axes:[{key:'detail',label:'종류',values:['A']},{key:'color',label:'색상',values:[]},{key:'size',label:'사이즈',values:['M']}],option_pricing:{A:0}})};
await act(async()=>{renderer=TestRenderer.create(React.createElement(Form,{activeBroadcastId:null,initialProduct:comboProduct}));});
assert.equal(toggle().props.checked,true,'existing combo custom field must remain editable');
await act(async()=>renderer.root.findByProps({'aria-label':'직접입력 칸 제목'}).props.onChange({target:{value:'주문 옵션'}}));
await act(async()=>buttons().find(button=>text(button)==='저장').props.onClick());
assert.equal(JSON.parse(saved.values.product_note).custom_input_label,'주문 옵션');
await act(async()=>renderer.unmount());
console.log('PASS existing combo custom input remains editable');
