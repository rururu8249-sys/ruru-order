import assert from 'node:assert/strict';
import fs from 'node:fs';
import React from 'react';
import Renderer,{act} from 'react-test-renderer';
import {createUiLoader} from './admin-ui-test-loader.mjs';
globalThis.IS_REACT_ACT_ENVIRONMENT=true;
assert.ok(fs.existsSync('components/admin-live/quick-product/PhotoColorSampler.tsx'),'photo sampling needs an explicit preview/apply flow');
let applied=[],closed=0,revoked=[];
const oldURL=globalThis.URL;
globalThis.URL={createObjectURL:()=> 'blob:test',revokeObjectURL:url=>revoked.push(url)};
globalThis.document={createElement:()=>({width:0,height:0,getContext:()=>({drawImage(){},getImageData:()=>({data:new Uint8ClampedArray([10,20,30,255])})})})};
const Sampler=createUiLoader()('components/admin-live/quick-product/PhotoColorSampler.tsx').default;
let tree;await act(async()=>{tree=Renderer.create(React.createElement(Sampler,{label:'모카',onApply:hex=>applied.push(hex),onClose:()=>closed++}));});
const file=()=>tree.root.findByProps({type:'file'});
await act(async()=>file().props.onChange({target:{files:[{type:'image/png',size:100}],value:'x'}}));
assert.equal(applied.length,0,'upload alone cannot change saved color');
const image=()=>tree.root.findByType('img');
await act(async()=>image().props.onClick({clientX:50,clientY:25,currentTarget:{naturalWidth:100,naturalHeight:100,getBoundingClientRect:()=>({left:0,top:0,width:100,height:100})}}));
assert.equal(applied.length,0,'point sampling only previews until apply');
await act(async()=>tree.root.findByProps({'aria-label':'선택한 색 적용'}).props.onClick());
assert.deepEqual(applied,['#0A141E']);
await act(async()=>file().props.onChange({target:{files:[],value:''}}));
await act(async()=>tree.root.findByProps({'aria-label':'사진 색상 추출 취소'}).props.onClick());
assert.equal(closed,1);assert.equal(applied.length,1);
await act(async()=>tree.unmount());assert.deepEqual(revoked,['blob:test']);
globalThis.URL=oldURL;
console.log('PASS photo sampling preview, explicit apply, cancel and URL cleanup');
