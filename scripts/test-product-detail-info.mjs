import assert from 'node:assert/strict';
const model=await import('../lib/productDetailInfo.ts').catch(()=>({}));
assert.equal(typeof model.resolveDetailInfo,'function','detail info resolver must exist');
const parent={product_note:JSON.stringify({spec_chips:['면 100%','국내배송']}),product_description:'브랜드 설명\n둘째 줄'};
assert.deepEqual(model.resolveDetailInfo(parent),{chips:['면 100%','국내배송'],description:'브랜드 설명\n둘째 줄'});
assert.deepEqual(model.resolveDetailInfo(parent,{mode:'custom',chips:[],description:''}),{chips:[],description:''});
assert.deepEqual(model.resolveDetailInfo(parent,{mode:'hidden',chips:['비공개'],description:'비공개'}),{chips:[],description:''});
const draft={mode:'custom',chips:['😀'.repeat(12),'A','B','C','D','E','F'],description:'첫 줄\n다음 줄'};
const before=JSON.stringify(draft);
assert.deepEqual(model.resolveDetailInfo(parent,draft),{chips:['😀'.repeat(10),'A','B','C','D','E'],description:'첫 줄\n다음 줄'});
assert.equal(JSON.stringify(draft),before,'resolution leaves editing draft unchanged');
console.log('detail info model: PASS');
const {renameDetail,removeDetailRow}=await import('../lib/brandDetailTableOps.ts');
const info={mode:'custom',chips:['소재'],description:'개별 설명'};
const state={details:['A','B'],detailPlus:{},detailPhotos:{},photoSets:{},categories:{},options:{},hidden:[],variantRows:[],detailInfo:{A:info,B:{mode:'hidden',chips:[],description:''}}};
const renamed=renameDetail(state,'A','C');
assert.equal(renamed.ok,true);
assert.deepEqual(renamed.state.detailInfo,{C:info,B:state.detailInfo.B},'inline rename must carry exact detail info');
assert.deepEqual(state.detailInfo.A,info,'rename must not mutate saved state');
assert.equal(removeDetailRow(renamed.state,'C').state.detailInfo.C,undefined,'removed detail must not leave orphan information');
