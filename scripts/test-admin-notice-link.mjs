import assert from 'node:assert/strict';
import React from 'react';
import Renderer,{act} from 'react-test-renderer';
import {createUiLoader} from './admin-ui-test-loader.mjs';
globalThis.IS_REACT_ACT_ENVIRONMENT=true;
const settings=[{key:'popup_notice_title',value:'기존 제목'},{key:'popup_notice_text',value:'기존 본문'},{key:'popup_notice_bar',value:'기존 요약'}];
const notices=[{id:17,title:'배송 공지',content:'배송 본문',is_visible:true,is_pinned:false,category:'공지',sort_order:1},{id:18,title:'비공개 글',content:'비공개 본문',is_visible:false,is_pinned:false,category:'공지',sort_order:2}];
let failSettings=false,writes=[];
const db={from(table){
 const result={data:table==='settings'?settings:notices,error:table==='settings'&&failSettings?{message:'network'}:null};
 const query={select(){return this;},in(){return this;},order(){return this;},then(resolve,reject){return Promise.resolve(result).then(resolve,reject);},async upsert(rows){writes.push(rows);return {error:null};}};
 return query;
}};
const {default:Panel}=createUiLoader({'@/lib/supabase':{supabase:db},'@/lib/adminToast':{showAdminToast(){}},'@/lib/adminConfirm':{showAdminConfirm:async()=>true}})('components/admin-live/AdminLiveNoticePanel.tsx');
let ui;
await act(async()=>{ui=Renderer.create(React.createElement(Panel));});
const select=ui.root.findByProps({'aria-label':'상단에 표시할 공지'});
assert.equal(select.findAllByType('option').some(n=>n.children.includes('비공개 글')),false);
await act(async()=>select.props.onChange({target:{value:'17'}}));
assert.equal(ui.root.findAllByType('details').some(n=>n.findAllByType('textarea').some(t=>t.props.value==='기존 본문')),true,'arrival popup remains independent inside collapsed settings');
assert.equal(select.findAllByType('option')[0].children.join(''),'상단에 표시하지 않음');
const save=()=>ui.root.findAllByType('button').find(n=>n.props.onClick?.name==='save');
await act(async()=>save().props.onClick());
assert.equal(writes[0].find(r=>r.key==='popup_notice_id').value,'17');
assert.equal(writes[0].find(r=>r.key==='popup_notice_text').value,'기존 본문','linking must preserve legacy content');
await act(async()=>select.props.onChange({target:{value:''}}));
assert.ok(ui.root.findAllByType('textarea').some(n=>n.props.value==='기존 본문'));
await act(async()=>ui.root.findByProps({title:'등록 · 고정 · 순서'}).props.onClick());
const choose=ui.root.findAllByType('button').find(n=>n.props['aria-label']==='배송 공지를 상단 공지로 선택');
assert.ok(choose,'public notice list must offer direct banner selection');
await act(async()=>choose.props.onClick());
assert.equal(ui.root.findByProps({'aria-label':'상단에 표시할 공지'}).props.value,'17');
assert.equal(writes.length,1,'selection alone must not publish settings');
await act(async()=>ui.unmount());
failSettings=true;writes=[];
await act(async()=>{ui=Renderer.create(React.createElement(Panel));});
assert.equal(save().props.disabled,true);
await act(async()=>save().props.onClick());
assert.equal(writes.length,0,'load failure must not save defaults');
await act(async()=>ui.unmount());
console.log('PASS admin public notice selection, legacy preservation and failed-load save guard');
