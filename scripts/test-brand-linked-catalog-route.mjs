import assert from 'node:assert/strict';
import fs from 'node:fs';
import {createUiLoader} from './admin-ui-test-loader.mjs';
const path='app/api/product-brand-catalog/route.ts';
assert.ok(fs.existsSync(path),'public catalog boundary must exist without exposing privileged product data');
process.env.NEXT_PUBLIC_SUPABASE_URL='https://example.supabase.co';
process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY='public-key';
process.env.SUPABASE_SERVICE_ROLE_KEY='private-key';
let calls=0,failed=false;
const rows=[{id:1,product_name:'브랜드'},{id:2,product_name:'원본'},{id:3,status:'숨김'}];
const links=[{source_id:2,parent_id:1,detail_name:'NEW',original_name:'원본',moved_at:'2026-10-05T00:00:00Z'},{source_id:3,parent_id:1,detail_name:'HIDDEN',original_name:'숨김',moved_at:'2026-10-05T00:00:00Z'},{source_id:4,parent_id:1,detail_name:'RLS DENIED',original_name:'비공개',moved_at:'2026-10-05T00:00:00Z'}];
const {POST}=createUiLoader({'@supabase/supabase-js':{createClient:(_url,key)=>({from:table=>{
  calls++;
  assert.equal(table,key==='public-key'?'products':'product_brand_links','service key must never read or return products');
  let ids=[];
  const q={select:()=>q,in:(_field,values)=>{ids=values;return q;},or:()=>q,order:()=>q,range:()=>q,then:resolve=>Promise.resolve({data:key==='public-key'?rows.filter(row=>ids.includes(String(row.id))):links,error:failed?{message:'secret database detail'}:null}).then(resolve)};
  return q;
}})}})(path);
const request=body=>({json:async()=>body});
assert.equal((await POST(request({ids:['1 OR TRUE']}))).status,400);
assert.equal(calls,0,'invalid IDs cannot reach database');
assert.equal((await POST(request({ids:Array.from({length:101},(_,i)=>String(i+1))}))).status,400);
const response=await POST(request({ids:['1']}));
assert.equal(response.status,200);
const data=await response.json();
assert.deepEqual(data.links,[{sourceId:'2',parentId:'1',detailName:'NEW',originalName:'원본',movedAt:'2026-10-05T00:00:00Z'}]);
assert.deepEqual(data.products.map(row=>row.id),[1,2],'hidden or RLS-inaccessible products must not be returned');
failed=true;
const bad=await POST(request({ids:['1']}));
assert.equal(bad.status,503);
assert.ok(!JSON.stringify(await bad.json()).includes('secret database detail'),'internal DB errors must remain private');
console.log('PASS catalog validation, RLS product reads, hidden sources and sanitized failures');
