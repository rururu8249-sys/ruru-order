import assert from 'node:assert/strict';
import React from 'react';
import TestRenderer,{act} from 'react-test-renderer';
import {createUiLoader} from './admin-ui-test-loader.mjs';
globalThis.IS_REACT_ACT_ENVIRONMENT=true;
globalThis.window={innerWidth:1200,addEventListener(){},removeEventListener(){},dispatchEvent(){}};
globalThis.document={addEventListener(){},removeEventListener(){}};
const {default:Form}=createUiLoader({'@/lib/supabase':{supabase:{}},'@/lib/adminToast':{showAdminToast(){}},'@/lib/adminConfirm':{showAdminConfirm:async()=>true}})('components/admin-live/quick-product/QuickProductFastForm.tsx');
const product={id:9001,product_name:'브랜드',price:1000,stock:0,color_options:['A','B'],product_note:JSON.stringify({brand_group:{enabled:true,detail_options:{A:{colors:[],sizes:['M'],variants:[]},B:{colors:[],sizes:['S'],variants:[]}},detail_info:{A:{mode:'custom',chips:['면'],description:'A 설명'},B:{mode:'custom',chips:['실크'],description:'B 설명'}}},combo_mode:true,combo_detail_values:['A','B'],option_axes:[{key:'detail',label:'종류',values:['A','B']}]})};
let renderer;
await act(async()=>{renderer=TestRenderer.create(React.createElement(Form,{activeBroadcastId:null,initialProduct:product,initialDetailName:'A'}));});
const buttons=()=>renderer.root.findAllByType('button');
const text=node=>node.children.map(child=>typeof child==='string'?child:typeof child==='object'?text(child):'').join('');
const infoTab=()=>buttons().find(button=>text(button)==='한눈에 정보·상세설명');
assert.ok(infoTab(),'detail editor must expose information section');
await act(async()=>infoTab().props.onClick());
assert.equal(renderer.root.findByProps({'aria-label':'상세설명'}).props.value,'A 설명');
await act(async()=>renderer.root.findByProps({'aria-label':'상세설명'}).props.onChange({target:{value:'수정 초안'}}));
const dialog=renderer.root.findByProps({'aria-label':'세부상품 수정'});
await act(async()=>dialog.findAllByType('button').find(button=>text(button)==='취소').props.onClick());
assert.equal(product.product_note.includes('수정 초안'),false,'cancel cannot modify original snapshot');
await act(async()=>buttons().find(button=>text(button)==='수정').props.onClick());
await act(async()=>infoTab().props.onClick());
assert.equal(renderer.root.findByProps({'aria-label':'상세설명'}).props.value,'A 설명','reopening restores saved information, not cancelled draft');
await act(async()=>renderer.root.findByProps({'aria-label':'상세설명'}).props.onChange({target:{value:'A 저장내용\n둘째 줄'}}));
await act(async()=>buttons().find(button=>text(button)==='변경내용 적용').props.onClick());
await act(async()=>buttons().find(button=>text(button)==='수정').props.onClick());
await act(async()=>infoTab().props.onClick());
assert.equal(renderer.root.findByProps({'aria-label':'상세설명'}).props.value,'A 저장내용\n둘째 줄','apply keeps changes for reopening within parent draft');
await act(async()=>renderer.root.findByProps({'aria-label':'세부상품 수정'}).findAllByType('button').find(button=>text(button)==='취소').props.onClick());
await act(async()=>buttons().filter(button=>text(button)==='수정')[1].props.onClick());
await act(async()=>infoTab().props.onClick());
assert.equal(renderer.root.findByProps({'aria-label':'상세설명'}).props.value,'B 설명','editing A cannot overwrite B');
await act(async()=>renderer.unmount());
console.log('detail form: exact selection and cancelled draft PASS');
