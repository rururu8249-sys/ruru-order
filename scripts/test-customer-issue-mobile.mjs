import assert from 'node:assert/strict';
import React from 'react';
import Renderer, {act} from 'react-test-renderer';
import {createUiLoader} from './admin-ui-test-loader.mjs';
globalThis.IS_REACT_ACT_ENVIRONMENT = true;
const load = createUiLoader({'@/lib/supabase': {supabase: {}}});
const {IssueCard} = load('components/admin-live/AdminLiveCustomerIssueRail.tsx');
assert.equal(typeof IssueCard, 'function', 'issue row must be independently renderable for mobile verification');
const task = {id:'fixture',status:'open',customer_nickname:'검증 고객',customer_name:'검증',related_product:'긴 상품명 · 베이지 / XXL · 2개',body:'내용: 반품 도착 확인 후 환불 예정\n계좌 확인 필요',created_at:'2026-10-10T00:00:00Z'};
let opened = 0, resolved = 0, selected = 0;
let tree;
let onResize;
const memoElement={scrollHeight:40,clientHeight:40};
globalThis.ResizeObserver=class {constructor(callback){onResize=callback;} observe(){} disconnect(){}};
await act(async()=>{tree=Renderer.create(React.createElement(IssueCard,{task,index:0,onProcess:t=>{assert.equal(t,task);opened++;},onResolve:t=>{assert.equal(t,task);resolved++;},onToggleSelect:t=>{assert.equal(t,task);selected++;},amount:{head:'119,000원',sub:'상품금액'}}),{createNodeMock:()=>memoElement});});
const row = tree.root.findAllByType('div')[0];
assert(row.props.className.includes('grid-cols-[36px_minmax(0,1fr)]'), 'mobile row must fit its container, not a fixed six-column desktop grid');
const content = tree.root.findByProps({'data-issue-content':true});
assert(content.props.className.includes('col-span-2'), 'issue content uses full card width');
assert(JSON.stringify(tree.toJSON()).includes('119,000원'));
assert(JSON.stringify(tree.toJSON()).includes('반품 도착 확인 후 환불 예정'));
const button = label=>tree.root.findAllByType('button').find(b=>b.children.join('')===label);
const event = {stopPropagation(){}};
assert.equal(typeof onResize,'function','memo must remeasure when viewport change clamps desktop content');
memoElement.scrollHeight=80;
await act(async()=>onResize());
assert(button('…더보기'),'desktop-clamped content retains a more action after resizing');
await act(async()=>button('열기').props.onClick(event));
assert.equal(opened,1); assert.equal(resolved,0,'opening details never resolves an issue');
await act(async()=>tree.root.findByType('input').props.onChange());
assert.equal(selected,1); assert.equal(resolved,0,'selection never resolves an issue');
await act(async()=>button('해결완료').props.onClick(event));
assert.equal(resolved,1,'existing explicit resolution action is retained');
await act(async()=>tree.update(React.createElement(IssueCard,{task,index:0,busy:true,onProcess(){},onResolve(){}})));
const busyButtons=tree.root.findAllByType('button').filter(b=>b.children.join('')==='처리중…');
assert.equal(busyButtons.length,1);
assert(busyButtons.every(b=>b.props.disabled));
let restored=0,unresolved=0,purged=0;
await act(async()=>tree.update(React.createElement(IssueCard,{task:{...task,status:'resolved',is_resolved:true},index:0,onProcess(){},onResolve(){},onUnresolve(){unresolved++;}})));
await act(async()=>button('미해결로').props.onClick(event));
assert.equal(unresolved,1);
assert.equal(button('해결완료'),undefined);
await act(async()=>tree.update(React.createElement(IssueCard,{task:{...task,status:'deleted'},index:0,onProcess(){throw Error('deleted row must not open');},onResolve(){},onRestore(){restored++;},onPurge(){purged++;}})));
await act(async()=>button('되살리기').props.onClick());
await act(async()=>button('영구삭제').props.onClick());
assert.equal(restored,1); assert.equal(purged,1);
await act(async()=>tree.unmount());
console.log('PASS customer issue mobile content, amount and separate action handlers');
