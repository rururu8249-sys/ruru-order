import assert from 'node:assert/strict';
import fs from 'node:fs';
const page = fs.readFileSync('app/order/page.tsx', 'utf8');
const form = fs.readFileSync('components/order/OrderCustomerInfoFormCard.tsx', 'utf8');
const editor = fs.readFileSync('components/customer/CustomerInfoEditBottomSheet.tsx', 'utf8');
const watch = fs.readFileSync('components/order/OrderBroadcastWatch.tsx', 'utf8');
const kakao = 'https://t1.kakaocdn.net/mapjsapi/bundle/postcode/prod/postcode.v2.js';
const title = '        {howToOpen && !liveWatchShown && !liveBootCover ? (';
assert(page.includes(`scriptUrl="${kakao}"`), '공식 카카오 주소검색 CDN 누락');
assert.equal(page.split('<KakaoPostcodeEmbed').length - 1, 1, '주소검색 UI 중복');
assert.equal(page.split('<CustomerToastNotice').length - 1, 1, '신규고객 오류 안내 UI 중복');
assert(page.indexOf('<KakaoPostcodeEmbed') < page.indexOf(title), '주소검색 시트가 기존고객 gate 내부에 있음');
assert(page.indexOf('<CustomerToastNotice') < page.indexOf(title), '신규고객에게 저장 오류 토스트 안 보임');
assert(!page.includes('setManualAddressOpen('), '직접입력 fallback 이 남음');
assert(!page.includes('<CustomerManualAddressPanel'), '직접입력 팝업이 남음');
assert(/isFirstInfoEntry && !\/\^\\d\{5\}\$\//.test(page) || page.includes('isFirstInfoEntry && !/^\\d{5}$/.test'), '신규 고객 우편번호 검증 누락');
assert(form.includes('readOnly\n              onClick={onOpenAddressSearch}'), '신규고객 기본주소 직접수정 허용');
assert(!form.includes('onAddressChange(event.target.value)'), '신규 고객 직접입력 콜백 남음');
assert(editor.includes('value={addrForm.address} readOnly onClick={handleAddressSearch}'), '배송지관리 기본주소 직접수정 허용');
assert(editor.includes('!/^\\d{5}$/.test(String(addrForm.zipcode || ""))'), '배송지 검색 선택 검증 누락');
assert(page.includes('setAddress(nextAddress);') && page.includes('setZipcode(nextZipcode);'), '주소와 우편번호 동시 저장 연결 누락');
assert(page.includes('setHasSavedInfo(true);') && page.includes('scrollToProductInput();'), '신규정보 저장 후 상품화면 이동 누락');
assert(watch.includes('유튜브로 방송 보기') && watch.includes('https://www.youtube.com/watch?v=${videoId}'), '방송 시청 버튼 연결 회귀');
console.log('PASS: 신규/기존 주소검색 공통 UI, Kakao CDN, 직접입력 차단, 우편번호 저장, 정보 저장→상품 및 방송 버튼 연결 (정적 회귀검사)');
