import assert from 'node:assert/strict';
import {selectWorkScope,uniqueWorkOrders,inShopDayScope,inBroadcastScope} from '../lib/adminWorkScope.ts';
const mk=(id,bc,at,more={})=>({id,groupId:id,orderNo:'O-'+id,createdAt:at,submittedAt:at,broadcastId:bc,broadcastName:'',paymentStatus:'paid',items:[{id:'1',productName:'p',qty:1}],...more});
const bc='aaaaaaaa-aaaa-aaaa-aaaa-aaaaaaaaaaaa', b={id:bc,dateKey:'2026-11-18',label:'방송 A'};
const live=mk('1',bc,'2026-11-18T13:00:00Z');
const shop=mk('2',null,'2026-11-18T13:00:00Z');
const old=mk('3',null,'2026-11-17T13:00:00Z');
const pulled=mk('4',null,'2026-11-17T13:00:00Z',{pickPull:{pulledFor:'2026-11-18',broadcastId:bc,target:'방송 A',originalOrderId:'4'}});
const all=[live,shop,old,pulled];
const base={allOrders:all,currentOrders:[live],selectedOrders:[old],broadcasts:[b]};
assert.deepEqual(selectWorkScope({...base,kind:'current'}).map(o=>o.id),['1']);
assert.deepEqual(selectWorkScope({...base,kind:'selected'}).map(o=>o.id),['3']);
assert.deepEqual(selectWorkScope({...base,kind:'broadcast',chosenBroadcastIds:[bc]}).map(o=>o.id),['1','4']);
assert.deepEqual(selectWorkScope({...base,kind:'shop',chosenShopDays:['2026-11-18']}).map(o=>o.id),['2']);
assert.deepEqual(selectWorkScope({...base,kind:'shop',chosenShopDays:['2026-11-17','2026-11-18']}).map(o=>o.id),['2','3']);
assert.deepEqual(selectWorkScope({...base,kind:'broadcast',chosenBroadcastIds:[]}),[]);
assert.equal(inBroadcastScope(pulled,b),true);
assert.equal(inShopDayScope(pulled,'2026-11-18'),false);
assert.equal(inShopDayScope(shop,'2026-11-18'),true);
assert.deepEqual(uniqueWorkOrders([live,live]).map(o=>o.id),['1']);
console.log('PASS work-scope: current, checked, selected broadcasts, shop dates, transferred items, dedupe');
