import assert from 'node:assert/strict';
import {createUiLoader} from './admin-ui-test-loader.mjs';
const load=createUiLoader();
let implementation;
try {implementation=load('lib/voiceAutomation.ts');} catch {}
assert.ok(implementation,'voice budget gate and capture rules must exist');
const {voiceCostBound,withVoiceBudget,voiceDisplayState,resolveCaptureCommand}=implementation;
assert.ok(voiceCostBound({kind:'transcription',seconds:360})>=185);
assert.throws(()=>voiceCostBound({kind:'transcription',seconds:NaN}));
assert.throws(()=>voiceCostBound({kind:'context',inputTokenBound:-1,outputTokenBound:200}));
let calls=0;
const invoke=async()=>{calls++; return 'ok'};
assert.equal((await withVoiceBudget(async()=>({allowed:false,reason:'budget'}),invoke)).executed,false); assert.equal(calls,0);
await assert.rejects(withVoiceBudget(async()=>{throw new Error('db down')},invoke));assert.equal(calls,0);
assert.equal((await withVoiceBudget(async()=>({allowed:true}),invoke)).value,'ok');assert.equal(calls,1);
await assert.rejects(withVoiceBudget(async()=>({allowed:true}),async()=>{throw new Error('unknown outcome')}),'no retries or credit release on unknown failure');
const now=Date.now();
const row={enabled:true,cap_krw:40000,committed_krw:32000,worker_seen_at:new Date(now).toISOString(),stop_reason:null};
assert.equal(voiceDisplayState(row,true,now),'warning');
assert.equal(voiceDisplayState({...row,worker_seen_at:new Date(now-31000).toISOString()},true,now),'offline');
assert.equal(voiceDisplayState({...row,enabled:false,stop_reason:'budget'},false,now),'budget_stopped');
assert.equal(voiceDisplayState(null,false,now),'not_ready');
assert.equal(voiceDisplayState({...row,enabled:false,stop_reason:'worker'},true,now),'offline','a stopped worker is an interruption, not never-started setup');
const target={productId:'748',detailName:'MC-311 블랙'};
assert.equal(resolveCaptureCommand('상품 사진 저장','상품 사진 저장',target).action,'capture');
for(const phrase of ['상품 사진 저장할까요','상품 사진 저장 하지마','사진 저장','상품 사진 저장이라고 말하면 되나요']) assert.equal(resolveCaptureCommand(phrase,'상품 사진 저장',target).action,'ignore');
assert.equal(resolveCaptureCommand('상품 사진 저장','상품 사진 저장',null).action,'hold');
assert.deepEqual(resolveCaptureCommand('상품 사진 저장!','상품 사진 저장',target).target,target);
console.log('PASS budget gate, conservative cost bound, readiness states, exact trigger with known variant');
