import assert from 'node:assert/strict';
import { buildCompactConversationPrompt,shouldFallbackModel,eligibleTestChatSession } from '../lib/liveAutomationCompactPrompt.ts';
assert.equal(shouldFallbackModel({text:null,note:'gemini-3.5-flash-lite:timeout'}),true);
assert.equal(shouldFallbackModel({text:null,note:'gemini-3.5-flash-lite:http_503'}),true);
assert.equal(shouldFallbackModel({text:null,note:'gemini-3.5-flash-lite:quota'}),true);
