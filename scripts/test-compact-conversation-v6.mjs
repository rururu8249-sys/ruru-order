const clock=Date.parse('2026-11-18T21:00:00+09:00');
const present=new Set(['s1']);
assert.equal(eligibleTestChatSession({id:'s1',watching:true,last_ack_at:new Date(clock-15000).toISOString()},present,clock),true);
assert.equal(eligibleTestChatSession({id:'s2',watching:true,last_ack_at:new Date(clock-15000).toISOString()},present,clock),false);
assert.equal(eligibleTestChatSession({id:'s1',watching:false,last_ack_at:new Date(clock-15000).toISOString()},present,clock),false);
assert.equal(eligibleTestChatSession({id:'s1',watching:true,last_ack_at:new Date(clock-90000).toISOString()},present,clock),false);
const message=(id,body,actorId=null,botRef=null)=>({id,body,nickname:'사람',automation_actor_id:actorId,bot_ref:botRef});
const base={mode:'live',cardText:'MC-352 아이보리 / 색상 아이보리 / 사이즈 0,1,2',actors:[{nickname:'달콩',own:['아이보리 예쁘네요']},{nickname:'별빛'}], messages:[message(3,'지금 결제계좌 알려주세요'),message(2,'감사해요'),message(1,'내 주문정보 12345',null,'o:secret')],pendingHumanId:3,styleSummary:'실제 고객 말길이 중앙 16자',realOrderProducts:['MC-352']};
const prompt=buildCompactConversationPrompt(base);
assert.ok(prompt.includes('#3 실제 사람: 지금 결제계좌 알려주세요'));
assert.ok(prompt.includes('응답 판단 대상: #3'));
assert.ok(!prompt.includes('12345'), 'order bot content must be excluded');
assert.ok(prompt.includes('주문/장바구니 자동 알림: 1건/0건'));
assert.ok(prompt.includes('MC-352 아이보리'));
assert.ok(prompt.includes('다른 테스트 계정이 다시 묻지 마라'));
assert.ok(prompt.length < 5200, `prompt too large: ${prompt.length}`);
assert.equal(buildCompactConversationPrompt({...base,mode:'paused'}).includes('방송 일시정지'),true);
assert.equal(buildCompactConversationPrompt({...base,mode:'replay'}).includes('방송 종료'),true);
const many=buildCompactConversationPrompt({...base,actors:Array.from({length:40},(_,i)=>({nickname:'actor-'+i})),messages:Array.from({length:80},(_,i)=>message(80-i,'짧은 채팅 테스트'))});
assert.ok(many.length < 6700, `unbounded prompt: ${many.length}`);
assert.ok(!many.includes('actor-39'), 'roster capped');
assert.ok(many.includes('#80'), 'recent messages retained');
assert.ok(!many.includes('#1 '), 'old messages excluded');
console.log(`PASS V6 compact prompt semantics; ${prompt.length} chars normal, ${many.length} bounded`);
