import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';
const db = new PGlite();
const bc = '00000000-0000-4000-8000-000000000001';
const worker = '00000000-0000-4000-8000-000000000002';
const q = async (sql, args=[]) => (await db.query(sql,args)).rows;
try {
  await db.exec(`create role anon; create role authenticated; create role service_role bypassrls; create table broadcasts(id uuid primary key,status text,is_deleted boolean default false); insert into broadcasts values('${bc}','ON',false); grant select on broadcasts to service_role;`);
  await db.exec(await fs.readFile('supabase/migrations/20261111093227_voice_automation_budget.sql','utf8'));
  assert.equal((await q("select to_regclass('public.voice_budgets') as t"))[0].t,'voice_budgets','budget ledger must exist');
  await db.exec('set role service_role');
  const configure = (action,cap=40000) => q('select voice_configure($1,$2,$3,$4) v',[bc,action,cap,'상품 사진 저장']);
  await configure('save');
  await assert.rejects(configure('resume'),/worker_not_ready/);
  await q('select voice_worker_claim($1,$2,$3,$4)',[bc,worker,'rates-2026-11-11',2000]);
  await configure('resume');
  const reserve = (id,amount,version='rates-2026-11-11') => q('select voice_reserve($1,$2,$3,$4,$5,$6) v',[bc,worker,id,'context',amount,version]).then(r=>r[0].v);
  assert.equal((await reserve('bad-rate',10,'wrong-policy')).allowed,false,'worker pricing must match locked policy');
  assert.equal((await reserve('one',10000)).allowed,true);
  assert.equal((await reserve('one',10000)).allowed,false,'duplicate must never authorize another provider call');
  await assert.rejects(reserve('one',10001),/request_conflict/);
  const result=await Promise.all([reserve('two',20000),reserve('three',20000)]);
  assert.equal(result.filter(r=>r.allowed).length,1,'only one remaining reservation fits');
  let state=(await q('select * from voice_budgets'))[0];
  assert.equal(state.committed_krw,32000); assert.equal(state.stop_reason,'budget');
  assert.equal((await q("select count(*)::int n from voice_budget_events where kind='warning'"))[0].n,1);
  assert.equal((await reserve('four',1)).allowed,false,'stopped remains stopped even if small request fits');
  await configure('save',50000);
  assert.equal((await reserve('five',1)).allowed,false,'saving higher cap must not silently resume');
  await configure('resume',50000); assert.equal((await reserve('six',100)).allowed,true);
  await configure('stop',1000); assert.equal((await reserve('seven',1)).allowed,false,'stop must succeed with old cap from another tab');
  assert.equal((await q('select cap_krw from voice_budgets'))[0].cap_krw,50000,'stop must not change cap');
  assert.equal((await q('select committed_krw from voice_budgets'))[0].committed_krw,32100,'stop/restart must not reset spend');
  await db.exec('reset role');
  await q("update voice_budgets set worker_seen_at=now()-interval '1 minute'");
  await db.exec('set role service_role');
  await assert.rejects(configure('resume',50000),/worker_not_ready/);
  await db.exec('reset role; set role anon');
  await assert.rejects(q('select * from voice_budgets'),/permission denied/);
  await assert.rejects(configure('save'),/permission denied/);
  await db.exec('reset role; set role authenticated');
  await assert.rejects(reserve('unauthorized',1),/permission denied/);
  console.log('PASS voice ledger: pre-debit, concurrency, duplicate denial, warning/stop persistence, explicit resume, stale worker, RLS/privileges');
} finally {await db.close();}
