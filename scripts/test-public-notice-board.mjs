import assert from 'node:assert/strict';
import React from 'react';
import Renderer,{act} from 'react-test-renderer';
import {createUiLoader} from './admin-ui-test-loader.mjs';
globalThis.IS_REACT_ACT_ENVIRONMENT=true;
const rows=Array.from({length:12},(_,i)=>({id:i+1,title:`공지 ${i+1}`,content:i===11?'특별 배송 안내':'본문',created_at:'2026-10-10',is_pinned:i===0,is_visible:true}));
let detailPending=[];
const db={from(table){assert.equal(table,'notices');return {select(){return this;},eq(key,value){if(key==='is_visible')assert.equal(value,true);return this;},order(){return this;},range:async()=>({data:rows,error:null}),maybeSingle(){return new Promise(resolve=>detailPending.push(resolve));}};}};
const load=createUiLoader({'@/lib/supabase':{supabase:db}});
const {loadPublicNotices}=load('lib/publicNoticeBoard.ts');
let ranges=[];
const batchDb={from(){return {select(){return this;},eq(){return this;},order(){return this;},async range(start,end){ranges.push([start,end]);return {data:start===0?Array.from({length:100},(_,i)=>({...rows[0],id:i+1})): [{...rows[1],id:101}],error:null};}};}};
assert.equal((await loadPublicNotices(batchDb)).length,101);
assert.deepEqual(ranges,[[0,99],[100,199]]);
const failDb={from(){return {select(){return this;},eq(){return this;},order(){return this;},range:async()=>({data:null,error:{message:'offline'}})};}};
await assert.rejects(()=>loadPublicNotices(failDb));
const {default:Board}=load('components/notice/PublicNoticeBoard.tsx');
function Host(){const [id,setId]=React.useState(null);return React.createElement(Board,{selectedId:id,onSelect:setId});}
let ui;await act(async()=>{ui=Renderer.create(React.createElement(Host));});
const text=()=>JSON.stringify(ui.toJSON());
const button=(label)=>ui.root.findAllByType('button').find(b=>b.props['aria-label']===label||b.children.join('')===label);
assert.match(text(),/공지 10/);assert.doesNotMatch(text(),/공지 11/);
await act(async()=>button('2페이지').props.onClick());
assert.match(text(),/공지 11/);assert.doesNotMatch(text(),/공지 10/);
await act(async()=>button('공지 11 읽기').props.onClick());
assert.match(text(),/공지를 불러오는 중/);
await act(async()=>detailPending.shift()({data:rows[10],error:null}));
await act(async()=>button('목록').props.onClick());
assert.equal(button('2페이지').props['aria-current'],'page');
await act(async()=>ui.root.findByType('input').props.onChange({target:{value:'특별 배송'}}));
await act(async()=>ui.root.findByType('form').props.onSubmit({preventDefault(){}}));
assert.match(text(),/공지 12/);assert.doesNotMatch(text(),/공지 11/);
assert.equal(button('2페이지'),undefined);
await act(async()=>button('공지 12 읽기').props.onClick());
