import assert from 'node:assert/strict';
import React from 'react';
import TestRenderer,{act} from 'react-test-renderer';
import {createUiLoader} from './admin-ui-test-loader.mjs';
globalThis.IS_REACT_ACT_ENVIRONMENT=true;
globalThis.window={innerWidth:1200,addEventListener(){},removeEventListener(){},dispatchEvent(){}};
globalThis.document={addEventListener(){},removeEventListener(){}};
let saved;
const load=createUiLoader({'@/lib/supabase':{supabase:{}},'@/lib/adminCatalogWrite':{adminCatalogWrite:async payload=>{saved=payload;return {data:{id:9001},error:null};}},'@/lib/adminToast':{showAdminToast(){}},'@/lib/adminConfirm':{showAdminConfirm:async()=>true}});
const {default:Form}=load('components/admin-live/quick-product/QuickProductFastForm.tsx');
const product={id:9001,product_name:'셔츠',price:10000,stock:0,color_options:['베이지'],size_options:['M','L'],product_note:JSON.stringify({stock_management_enabled:false,stock_mode:'option',stock_variants:[{color:'베이지',size:'M',stock:0,manual_soldout:true},{color:'베이지',size:'L',stock:0}]})};
const text=node=>node.children.map(child=>typeof child==='string'?child:typeof child==='object'?text(child):'').join('');
product.__catalog_edit_version='a'.repeat(32);
let renderer;
await act(async()=>{renderer=TestRenderer.create(React.createElement(Form,{activeBroadcastId:null,initialProduct:product}));});
const openDetails=async()=>{const b=renderer.root.findAllByType('button').find(b=>text(b).includes('자세히 열기'));if(b) await act(async()=>b.props.onClick());};
await openDetails();
const getSoldout=label=>renderer.root.findAllByType('input').find(b=>b.props.type==='checkbox'&&b.props['aria-label']===label);
assert.ok(getSoldout('베이지 / M 품절'),'manual soldout checkbox must appear with inventory OFF');
assert.equal(getSoldout('베이지 / M 품절').props.checked,true);
assert.equal(getSoldout('베이지 / L 품절').props.checked,false);
assert.equal(text(renderer.root).includes('판매중'),false,'normal options need no selling status label');
await act(async()=>getSoldout('베이지 / L 품절').props.onChange({target:{checked:true}}));
await act(async()=>renderer.root.findAllByType('button').find(b=>text(b)==='저장').props.onClick());
assert.ok(saved,'form must save when manual soldout and inventory OFF');
assert.equal(JSON.parse(saved.values.product_note).stock_management_enabled,false);
assert.deepEqual(JSON.parse(saved.values.product_note).stock_variants.map(v=>v.manual_soldout),[true,true]);
await act(async()=>renderer.unmount());
await act(async()=>{renderer=TestRenderer.create(React.createElement(Form,{activeBroadcastId:null,initialProduct:{...product,...saved.values}}));});
await openDetails();
assert.equal(getSoldout('베이지 / L 품절').props.checked,true,'saved state survives reopening');
await act(async()=>getSoldout('베이지 / M 품절').props.onChange({target:{checked:false}}));
await act(async()=>renderer.root.findAllByType('button').find(b=>text(b)==='저장').props.onClick());
assert.deepEqual(JSON.parse(saved.values.product_note).stock_variants.map(v=>v.manual_soldout),[false,true]);
await act(async()=>renderer.unmount());
const {isOptionManuallySoldOut}=load('lib/productOptionAvailability.ts');
for(const flag of [false,undefined,'false']) assert.equal(isOptionManuallySoldOut({stock_variants:[{color:'',size:'M',manual_soldout:flag}]},'없음','M'),false);
assert.equal(isOptionManuallySoldOut({stock_variants:[{color:'',size:'M',manual_soldout:true}]},'없음','M'),true);
const note={brand_group:{detail_options:{'BB-60':{}}},stock_variants:[{color:'BB-60 / 베이지',size:'M',manual_soldout:true}]};
assert.equal(isOptionManuallySoldOut(note,'베이지','M','BB-60'),true);
assert.equal(isOptionManuallySoldOut(JSON.stringify(note),'BB-60 / 베이지','M','BB-60'),true);
assert.equal(isOptionManuallySoldOut(note,'베이지','L','BB-60'),false);
const {buildRowsForDetail}=load('lib/brandDetailTableOps.ts');
assert.equal(buildRowsForDetail('BB-60',[],['M'],[{key:'BB-60__M',detail:'BB-60',colorOnly:'',color:'BB-60',size:'M',stock:5,manual_soldout:true}])[0].manual_soldout,true,'legacy empty color must preserve soldout when rebuilt as 없음');
assert.equal(buildRowsForDetail('BB-60',['베이지'],['M'],[{key:'BB-60 / 베이지__M',detail:'BB-60',colorOnly:'베이지',color:'BB-60 / 베이지',size:'M',stock:0,manual_soldout:true}])[0].manual_soldout,true);
console.log('PASS inventory OFF controls, save/reopen, restore selling, size-only, legacy brand and detail rebuild');
