import assert from 'node:assert/strict';
import {createUiLoader} from './admin-ui-test-loader.mjs';
const load=createUiLoader();
const {featuredProducts}=load('lib/liveFeaturedProducts.ts');
const {rotationIndex,transitionRotation}=load('lib/widgetRotationClock.ts');
const {liveWatchDetailProduct}=load('lib/liveFeaturedProducts.ts');
const legacy={id:'10',price:100,product_note:{brand_group:{enabled:true},combo_detail_values:['블랙','화이트'],option_pricing:{블랙:25},stock_management_enabled:true,stock_variants:[{color:'블랙',size:'M',stock:0},{color:'화이트',size:'M',stock:3}]}};
const black=liveWatchDetailProduct(legacy,'블랙');
assert.equal(black.price,125,'legacy detail surcharge must match the widget');
assert.equal(black.stock,0,'exhausted detail must not inherit sibling stock');
assert.equal(black.product_note.stock_variants.length,1);
const linked={id:'22',price:200,stock:5};
assert.equal(liveWatchDetailProduct({...legacy,__linked_order_sources:{화이트:linked}},'화이트'),linked);
const items=[{id:'10',name:'브랜드',brand:true,priceText:'최저가',soldOut:false,imageUrl:'',details:[{productId:'10',name:'블랙',priceText:'10원',imageUrl:'black',soldOut:false},{productId:'22',name:'화이트',priceText:'20원',imageUrl:'white',soldOut:false},{productId:'23',name:'품절',priceText:'30원',imageUrl:'',soldOut:true}]},{id:'30',name:'가방',priceText:'40원',imageUrl:'bag',soldOut:false}];
const config={mode:'selected',paused:false,targets:[{productId:'22',detailName:''},{productId:'10',detailName:'블랙'}]};
const selected=featuredProducts(items,config,[],true,null);
assert.deepEqual(selected.map(p=>[p.id,p.detailName,p.name]),[['10','화이트','화이트'],['10','블랙','블랙']]);
assert.equal(selected[0].imageUrl,'white');
assert.equal(featuredProducts(items,config,[],false,null).length,0,'OFF hides card and featured list');
assert.equal(featuredProducts(items,{...config,paused:true},[],true,null).length,2,'pause does not hide');
assert.equal(featuredProducts(items,{...config,targets:[]},[],true,null).length,0);
assert.equal(featuredProducts(items,{...config,mode:'all'},[],true,null).length,3);
assert.equal(featuredProducts(items,{...config,mode:'history'},[{productId:'30',detailName:''}],true,null)[0].id,'30');
assert.equal(featuredProducts(items,config,[],true,{productId:'30',detailName:''})[0].id,'30','pin wins');
assert.equal(featuredProducts(items,config,[],true,{productId:'99',detailName:''}).length,2,'unavailable pin falls back to shared rotation like the widget');
assert.deepEqual(featuredProducts([{...items[0],soldOut:true}],config,[],true,null).map(p=>p.name),['화이트'],'linked stock is independent from exhausted parent stock');
const start=transitionRotation(null,config,100000);
assert.equal(rotationIndex(start,3,106000),1);
const pause=transitionRotation(start,{...start,paused:true},106000);
assert.equal(rotationIndex(pause,3,900000),1);
const resume=transitionRotation(pause,{...pause,paused:false},900000);
assert.equal(rotationIndex(resume,3,900000),1);
assert.equal(rotationIndex(resume,3,904000),2);
assert.equal(rotationIndex(start,0,106000),0);
assert.equal(rotationIndex(transitionRotation(start,{...config,targets:[]},106000),3,106000),0);
console.log('PASS featured identities, shared controls and pause/resume clock');
