import assert from 'node:assert/strict';
import React from 'react';import Renderer,{act} from 'react-test-renderer';
import {createUiLoader} from './admin-ui-test-loader.mjs';
globalThis.IS_REACT_ACT_ENVIRONMENT=true;
globalThis.document={activeElement:null};globalThis.window={confirm:()=>true};
const calls=[];const defaults={title:'가위·바위·보 루루를 이겨라!',winners:1,rewardKind:'points',points:1000,gift:'',joinSeconds:300,pickSeconds:5,auto:true};
const game={state:null,admin:true,verified:true,winners:[],error:'',busy:false,now:Date.now(),setup:{revision:0,config:defaults},refresh:async()=>{},action:async(name,data)=>{calls.push({name,data});if(name==='saveSetup')game.setup={revision:1,config:{...data}};return true;}};
const {RpsAdmin}=createUiLoader({'./rps.css':{}})('components/rps/RpsAdmin.tsx');
let closed=0;let tree;await act(async()=>{tree=Renderer.create(React.createElement(RpsAdmin,{game,onClose(){closed++;},broadcastId:'A'}));});
const text=n=>typeof n==='string'?n:Array.isArray(n)?n.map(text).join(''):n?.children?.map(text).join('')??'';
const button=s=>tree.root.findAllByType('button').find(b=>text(b)===s);
const label=s=>tree.root.findAllByType('label').find(b=>text(b).startsWith(s));
assert.ok(button('저장'),'settings has Save before any recruitment');
assert.ok(!button('참가자 모집 시작'),'settings cannot start recruitment');
const points=label('포인트').findByType('input');assert.equal(points.props.value,'1,000');
await act(async()=>points.props.onChange({target:{value:'10000'}}));assert.equal(label('포인트').findByType('input').props.value,'10,000');
assert.match(text(tree.toJSON()),/무작위/);
await act(async()=>tree.root.findByType('form').props.onSubmit({preventDefault(){}}));
assert.deepEqual(calls.map(c=>c.name),['saveSetup']);assert.equal(calls[0].data.points,10000);
assert.equal(closed,1,'save closes settings and returns to broadcast game screen');
assert.ok(!button('참가자 모집 시작'),'settings never duplicates recruitment controls');
assert.ok(tree.root.findByProps({'aria-label':'모집 시간 분'}));assert.ok(tree.root.findByProps({'aria-label':'모집 시간 초'}));
assert.ok(!text(tree.toJSON()).includes('한 분당 포인트'));assert.ok(!text(tree.toJSON()).includes('루루의 손'));
// A newly started room must not inherit an unsaved draft for the next game.
await act(async()=>label('포인트').findByType('input').props.onChange({target:{value:''}}));
await act(async()=>label('이벤트 선물').findByType('select').props.onChange({target:{value:'none'}}));
assert.equal(button('저장').props.disabled,false,'hidden unused points cannot disable Save');
await act(async()=>tree.root.findByType('form').props.onSubmit({preventDefault(){}}));
assert.equal(calls.at(-1).data.points,1000,'unused points normalized');
await act(async()=>label('게임 제목').findByType('input').props.onChange({target:{value:'작성 중'}}));
const before=calls.length;
game.state={id:'new-room',status:'lobby',revision:game.setup.revision,round:0,...defaults,target:1};
await act(async()=>tree.update(React.createElement(RpsAdmin,{game,onClose(){closed++;}})));
await act(async()=>tree.root.findByType('form').props.onSubmit({preventDefault(){}}));
assert.equal(calls.length,before,'draft target changed: no live-room mutation');
assert.match(text(tree.toJSON()),/게임 상태가 바뀌었어요/);
await act(async()=>tree.unmount());console.log('PASS settings-only form, formatted points, save without recruitment, returns to broadcast, minutes/seconds controls');
