import assert from 'node:assert/strict';
import fs from 'node:fs';
import {createUiLoader} from './admin-ui-test-loader.mjs';
assert(fs.existsSync('lib/eventPlayback.ts'),'shared playback contract has not been implemented');
const {makePlayback,samplePlayback,eventSeed,calculateEventDurationMs}=createUiLoader()('lib/eventPlayback.ts');
const input={id:'fixture',kind:'roulette',status:'result',startedAt:'2030-01-01T00:00:00Z',durationMs:9200,participants:['A','B'],winners:['A']};
const p=makePlayback(input);assert(p,'valid result provides shared timeline');
assert.equal(p.key,'["roulette","fixture","2030-01-01T00:00:00Z",1]');
assert.deepEqual(makePlayback({...input,title:'changed',updated_at:'later'}),p);
assert.notEqual(makePlayback({...input,startedAt:'2030-01-01T00:00:01Z'}).key,p.key);
for(const patch of [{id:''},{startedAt:'bad'},{durationMs:5000},{durationMs:-1},{participants:[]},{winners:['absent']},{status:'closed'}])assert.equal(makePlayback({...input,...patch}),null);
assert.deepEqual(samplePlayback(p,p.startedAtMs-1),{phase:'waiting',elapsedMs:0});
assert.deepEqual(samplePlayback(p,p.startedAtMs+3000),{phase:'running',elapsedMs:3000});
assert.deepEqual(samplePlayback(p,p.startedAtMs+100000),{phase:'done',elapsedMs:9200});
assert.equal(eventSeed('abc'),440920331,'FNV-1a independently known vector');
assert.equal(calculateEventDurationMs('claw',['A','B'],['A'],0),7200);
assert.equal(calculateEventDurationMs('claw',['A','B'],['A'],1),15000);
assert.equal(calculateEventDurationMs('claw',['A','B'],['A'],2),22800);
// Opening 2800 + final duel 2000 + last-impact tail 900, independently timed.
assert.equal(calculateEventDurationMs('survival',['A','B','C'],['A'],0),5700);
assert(makePlayback({...input,kind:'survival',participants:['A','B','C'],durationMs:5900}),'old 5900ms records must remain playable');
assert.equal(calculateEventDurationMs('race',['A','B','C'],['A'],0),11320);
assert.equal(calculateEventDurationMs('race',['A','B','C'],['A','B'],0),11770);
assert.equal(calculateEventDurationMs('race',['A'],['A'],0),1);
console.log('PASS shared immutable timeline, legacy validation, duration and phase boundaries');
