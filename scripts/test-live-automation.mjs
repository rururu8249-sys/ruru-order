import assert from 'node:assert/strict';
import {createUiLoader} from './admin-ui-test-loader.mjs';
const load=createUiLoader();
let A, P;
try { A=load('lib/liveAutomation.ts'); P=load('lib/liveAutomationPersona.ts'); } catch {}
assert.ok(A && P, 'independent session scheduling and persona rules must exist');
assert.deepEqual([0,.2,.4,.6,.8,.999].map(n=>A.dwellMinutes(()=>n)),[5,9,14,28,46,120]);
assert.equal(A.orderWindow(1000,1000,()=>0),1201000);
assert.equal(A.orderWindow(1000,1000,()=>.999999),1201000);
assert.equal(A.orderWindow(1000,1000000,()=>0),2200000,'resume never catches up old slots');
assert.equal(A.questionWindow(600000,()=>0),570000);
assert.equal(A.questionWindow(600000,()=>.999999),510000);
assert.equal(A.orderTarget(5,3,()=>.99),3);
assert.equal(A.orderTarget(30,3,()=>.99),3);
assert.equal(A.orderTarget(30,0,()=>.99),0);
assert.equal(A.nicknameKey('  JENNY  '),'jenny');
assert.equal(A.canSubmitQuestion(1000,30999),false);
assert.equal(A.canSubmitQuestion(1000,31000),true);
assert.equal(A.canSubmitQuestion(1000,121000),true);
assert.equal(A.canSubmitQuestion(1000,121001),false);
const line={productId:'20',productName:'PD-1',color:'블랙',size:'M',unitPrice:100,qty:2};
assert.equal(A.validatePlannedLines([line],[{...line,available:2}]),true);
assert.equal(A.validatePlannedLines([line],[{...line,productName:'PD-2',available:2}]),false,'brand ID alone must not match');
assert.equal(A.validatePlannedLines([line],[{...line,available:1}]),false);
assert.equal(A.validatePlannedLines([line],[{...line,unitPrice:200,available:2}]),false);
assert.equal(A.validatePlannedLines([line],[]),false);
const personas=Array.from({length:12},(_,i)=>P.createPersona(i));
assert.equal(new Set(personas.map(p=>JSON.stringify(p))).size,12);
assert.deepEqual(personas[7],P.createPersona(7));
assert.equal(new Set(personas.map(p=>`${p.age}/${p.gender}`)).size,6);
assert.ok(new Set(personas.map(p=>P.personaLine(p,'greeting',0))).size>=8);
assert.ok(new Set(personas.map(p=>P.personaLine(p,'submitted',0))).size>=8);
assert.equal(P.duplicateLine('  안녕하세요~ ',['안녕하세요~']),true);
assert.equal(P.duplicateLine('색상은 어떤 게 더 밝나요?',['소매 길이가 궁금해요']),false);
assert.equal(P.safeConversationLine('AI 한도 초과로 잠시 테스트 중'),false);
assert.equal(P.safeConversationLine('방금 입금 완료했어요'),false);
assert.equal(P.safeConversationLine('옆모습도 보여주세요'),true);
