import assert from 'node:assert/strict';
import { detailProducts } from '../lib/productDetailModel.ts';
const model = await import('../lib/productBrandLinks.ts').catch(() => ({}));
assert.equal(typeof model.resolveBrandCatalog, 'function', 'linked catalog resolver must exist');
const parent = {id: 1, product_name: '브랜드', price: 129000, product_note: JSON.stringify({brand_group:{enabled:true,detail_options:{OLD:{sizes:['M']}}},option_pricing:{OLD:40000}})};
const source = {id:2,product_name:'상품명 없음-6',price:39000,stock:7,image_url:'actual.jpg',detail_image_urls:['actual.jpg','back.jpg'],color_options:['베이지'],size_options:['S','M'],product_note:JSON.stringify({stock_management_enabled:true,stock_variants:[{color:'베이지',size:'S',stock:3},{color:'베이지',size:'M',stock:4}]})};
const link={sourceId:'2',parentId:'1',detailName:'BB-NEW',originalName:source.product_name,movedAt:'2026-10-05T00:00:00Z'};
const before=JSON.stringify([parent,source]);
const catalog=model.resolveBrandCatalog([parent,source],[link]);
assert.deepEqual(catalog.roots.map(p=>p.id),[1]);
const detail=catalog.bySourceId.get('2');
assert.equal(detail.price,39000);
assert.equal(detail.sourceProductId,'2');
assert.deepEqual(detail.images,['actual.jpg','back.jpg']);
assert.deepEqual(detail.colors,['베이지']);
assert.deepEqual(detail.sizes,['S','M']);
assert.equal(detail.stock,7);
assert.deepEqual(detail.stockVariants,[{color:'베이지',size:'S',stock:3},{color:'베이지',size:'M',stock:4}]);
assert.equal(JSON.stringify([parent,source]),before,'must not mutate source or parent');
assert.deepEqual(catalog.detailsByParent.get('1')[0],detailProducts(parent)[0],'legacy detail remains unchanged');
assert.equal(model.resolveBrandCatalog([parent,{...source,price:0}],[link]).bySourceId.get('2').price,0);
assert.throws(()=>model.resolveBrandCatalog([parent],[link]),/unresolved.*source/i);
assert.throws(()=>model.resolveBrandCatalog([source],[link]),/unresolved.*parent/i);
assert.throws(()=>model.resolveBrandCatalog([parent,source],[link,link]),/duplicate/i);
assert.equal(model.resolveBrandCatalog([parent,{...source,status:'숨김'}],[link]).bySourceId.get('2').hidden,true);
assert.equal(model.resolveBrandCatalog([parent,{...source,status:'deleted'}],[link]).bySourceId.get('2').hidden,true);
assert.throws(()=>model.resolveBrandCatalog([parent,source],[{...link,detailName:'OLD 다른이름'}]),/duplicate.*code/i);
console.log('product brand links: PASS');
