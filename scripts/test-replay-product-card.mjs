import assert from 'node:assert/strict';
import {createUiLoader} from './admin-ui-test-loader.mjs';
const {replayProductTimeline,replayGroupIndex}=createUiLoader()('lib/replayProductCard.ts');
const video='abcdefghijk';
const items=[{id:'10',name:'브랜드',brand:true,priceText:'최저가',soldOut:false,details:[{productId:'22',name:'화이트',priceText:'20원',soldOut:false}]},{id:'30',name:'가방',priceText:'30원',soldOut:false},{id:'40',name:'품절',priceText:'40원',soldOut:true}];
const entry=(id,detail,seconds,videoId=video)=>[JSON.stringify([id,detail]),{videoId,seconds,capturedAt:1,recordedAt:'2026-11-11'}];
const catalog=new Map([entry('22','',100),entry('30','',200),entry('40','',300),entry('999','',400),entry('55','',1,'wrongvideo1')]);
const timeline=replayProductTimeline(catalog,items,video);
assert.deepEqual(timeline.map(g=>g.seconds),[100,200,300,400]);
assert.deepEqual(timeline[0].products.map(p=>[p.id,p.detailName]),[['10','화이트']]);
assert.equal(replayGroupIndex(timeline,null),-1);
assert.equal(replayGroupIndex(timeline,99),-1);
assert.equal(replayGroupIndex(timeline,100),0);
assert.equal(replayGroupIndex(timeline,199),0);
assert.equal(replayGroupIndex(timeline,200),1);
assert.equal(replayGroupIndex(timeline,110),0,'rewind returns earlier group');
assert.equal(timeline[replayGroupIndex(timeline,310)].products.length,0,'soldout segment must not retain prior product');
assert.equal(replayGroupIndex(timeline,500),3,'last boundary remains until end');
const same=replayProductTimeline(new Map([entry('22','',100),entry('30','',100)]),items,video);
assert.equal(same.length,1);assert.equal(same[0].products.length,2);
const alias=replayProductTimeline(new Map([entry('10','화이트',100)]),items,video);
assert.equal(alias[0].products[0].detailName,'화이트');
console.log('PASS replay timeline: boundaries, tied products, seek-back, linked routes, unavailable segments and video scope');
