import assert from 'node:assert/strict';
import React from 'react';
import Renderer,{act} from 'react-test-renderer';
import {createUiLoader} from './admin-ui-test-loader.mjs';
globalThis.IS_REACT_ACT_ENVIRONMENT=true;
let requests=[],selected=[];
globalThis.fetch=()=>new Promise(resolve=>requests.push(resolve));
const {default:Picker}=createUiLoader()('components/admin-live/BroadcastVideoHistoryPicker.tsx');
let tree;await act(async()=>{tree=Renderer.create(React.createElement(Picker,{disabled:false,selectedVideoId:'12345678901',onSelect:url=>selected.push(url)}));});
assert.equal(requests.length,0,'collapsed history does not fetch on every render');
const button=name=>tree.root.findAllByType('button').find(x=>JSON.stringify(x.props.children).includes(name));
await act(async()=>button('지난 영상').props.onClick());assert.equal(requests.length,1);
await act(async()=>requests[0]({ok:true,json:async()=>({items:[{videoId:'abcdefghijk',broadcastId:'b',title:'11월 1일 방송',date:'2026-11-01T01:00:00Z',introCount:5},{videoId:'12345678901',broadcastId:'c',title:'오늘 방송',date:'2026-11-11T01:00:00Z',introCount:0}]})}));
assert.equal(tree.root.findAllByType('img').length,2);
await act(async()=>tree.root.findByType('input').props.onChange({target:{value:'11-01'}}));
assert.equal(tree.root.findAllByType('img').length,1,'date search narrows history');
await act(async()=>button('이 영상 선택').props.onClick());
assert.deepEqual(selected,['https://www.youtube.com/watch?v=abcdefghijk']);
assert.equal(requests.length,1,'selection stages URL; no silent production mutation');
await act(async()=>tree.unmount());
await act(async()=>{tree=Renderer.create(React.createElement(Picker,{disabled:false,selectedVideoId:'',onSelect:()=>{}}));});
await act(async()=>button('지난 영상').props.onClick());await act(async()=>requests[1]({ok:false}));
assert(JSON.stringify(tree.toJSON()).includes('다시 불러오기'));
await act(async()=>button('다시 불러오기').props.onClick());assert.equal(requests.length,3);
await act(async()=>requests[2]({ok:true,json:async()=>({items:[]})}));
assert(JSON.stringify(tree.toJSON()).includes('저장된 영상이 없어요'));
await act(async()=>tree.unmount());
console.log('PASS history lazy open, thumbnail/date search, URL selection only and error retry');
