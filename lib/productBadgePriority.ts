// lib/productBadgePriority.ts
// 목적: 손님 상품카드 배지를 «몇 개까지 보여줄지» 한 곳에서 정한다.
// 주의: 표시 전용. 재고·금액·담기·배송비·입금 로직 없음.
//
// 왜 필요했나 (2026-09-20 실측)
// - 격자(2열)가 기본이 되면서 폰 420px에서 카드 폭이 167px.
//   배지 4개면 배지 줄만 42px(2줄), 5~6개면 3줄이 된다.
// - 업계 기준도 같은 방향: 「상품당 배지 1개, 카탈로그의 15~25%만」
//   (배지를 덕지덕지 붙이면 손님이 배지 자체를 안 보게 된다 — badge blindness)
//
// 우리 규칙
// - 정보 배지(info)는 «개수 제한 밖». 손님이 꼭 알아야 하는 사실이라 감추면 안 된다.
//   ✈️해외배송(배송 2~3주) / 🚚업체배송 / 🎁무료나눔 / 🛒바로구매(방송 중일 때만)
// - 마케팅 배지(promo)는 우선순위대로 최대 2개.
//   사장님이 직접 고른 배지를 자동 배지보다 위에 둔다.
//   단 「🔥 N개 남음」은 자동이지만 구체적 수치 + 긴급성이라 전환 효과가 가장 커서 1순위.

// 원칙: 사장님이 «직접 고른» 배지가 자동 배지보다 위.
//   딱 하나 예외가 「🔥 N개 남음」 — 자동이지만 구체적 수치 + 긴급성이라 전환 효과가 가장 크다.
//   「🏆 N개 판매」도 강한 신호지만 자동이므로 수동 배지 아래에 둔다.
//   (자동 집계가 사장님이 의도적으로 단 ⚡특가·마감임박을 밀어내면 그건 매출 손해다)
export const BADGE_PROMO_ORDER = [
  "low",        // N개 남음          — 재고. 숫자를 쓰는 유이한 배지(필수 정보)
  "special",    // 특가              (사장님 설정)
  "limit",      // 마감임박          (사장님 설정)
  "pick",       // 💖 루루픽         (사장님 설정 «전용» — 자동으로 붙이지 않는다)
  "holding",    // 여러 명이 담는 중  — 실시간 선점(3명 이상)
  "recommend",  // 📌 추천           (사장님 고정)
  "topSeller",  // 베스트            — 판매 순위 상위 3%  (무신사·쿠팡·네이버 공통 표준어 BEST)
  "repeat",     // 재구매            — 재구매 2명 이상   (쿠팡 「다시 구매」 계열)
  "trending",   // 급상승            — 최근 30일 판매   (무신사 실물 배지 그대로)
  "hot",        // 인기              — 사장님 설정 또는 판매 순위 상위 25%
  "new",        // 신상              — 사장님 설정 또는 등록 7일 이내
] as const;

// ============================================================
// 배지 기준선 — 왜 «숫자»를 거의 안 쓰는가
//
// 사장님 지적 두 가지가 같은 곳을 가리킨다.
//   ① «인기 없는 건 표시가 안 되면, 사람들 왜 안 사지? 나도 안 사야겠다 하는 거 아니야?»
//   ② «너무 적나라하게 몇 명 막 이러는 게 맞는 건지»
//
// ①은 이름이 있는 현상이다 — negative social proof(역효과 사회적 증거).
//   「오늘 1개 주문」 「1명이 보는 중」 같은 낮은 숫자는 그 상품을 «별로인 상품»으로 읽히게 한다.
//   안 보여주는 것만 못하다.
// ②도 맞다. 무신사가 숫자를 쓰는 건 「판매 2천개」처럼 «큰 수»일 때다.
//   우리 최고가 137개라 절대 수치를 쓰면 대부분 초라해 보인다.
//
// → 그래서 숫자를 쓰는 배지는 딱 둘만 남겼다.
//      「N개 남음」        재고는 구체적이어야 뜻이 산다(쿠팡도 「99% 남음」)
//      「오늘 N개 주문」    사장님이 좋다고 한 배지. 5개 이상일 때만 뜬다
//   나머지는 전부 «등급 이름»으로 바꿨다 — 최다판매 / 인기 / 요즘 잘나가요 /
//   재구매 많아요 / 여러 명이 담는 중. 이름 자체가 기준이라 숫자가 초라할 일이 없다.
//
// 그리고 «한 명만 사도 급상승» 같은 일이 없게, 등급은 전부 «순위»로 끊는다.
//   순위는 옆 상품과 겨뤄 이긴 자리라, 절대 수치가 작아도 초라하지 않다.
//
// 출처: fera.ai/blog/posts/avoid-negative-social-proof (낮은 수치의 역효과),
//       무신사 랭킹 실물(「급상승」·「판매 2천개」), 쿠팡 검색 실물(「99% 남음」)
// ============================================================

/** 「급상승」 — 최근 30일 판매 수량 기준. 무신사가 같은 뜻으로 쓰는 실물 배지명.
 *  숫자를 화면에 안 쓰므로(「급상승」으로만 뜬다) 기준을 후하게 줘도 초라해지지 않는다.
 *
 *  [2026-09-20 실측] 상품 696개의 최근 30일 판매 분포
 *     1개+ 55개 / 2개+ 41개 / 3개+ 35개 / 5개+ 28개 / 10개+ 18개 / 20개+ 11개
 *     (방송마다 상품이 바뀌어 최근 한 달에 팔린 상품 자체가 55개뿐이다)
 *
 *  사장님 «급상승은 좀 유하게, 기준이 빡세지 않게» → 5개(28개)에서 2개(41개)로 낮춘다. 약 1.5배.
 *  1개까지 낮추지 않은 이유도 사장님 말이다 — «한 명만 사도 급상승이라던지... 흠».
 *  한 달에 1개는 «급상승»이라 부르기 어렵다. 2개가 두 말을 모두 만족하는 지점이다. */
export const SOLD_RECENT_MIN_QTY = 2;

/** 「재구매」 — 재구매 고객 수 기준. 사람 수는 화면에 안 나온다.
 *  재구매 판정은 재구매율 리포트와 같은 기준(kakao_id 우선 · order_group_id 1건=1회 · 2건 이상).
 *  ※ 「재구매↑」 같은 화살표를 안 쓰는 이유: 우리 데이터는 «누적 인원»이지 «증가 추세»가 아니다.
 *    ↑는 사실과 다른 표시가 된다. */
export const REPEAT_BADGE_MIN_BUYERS = 2;

/** 「여러 명이 담는 중」 — 지금 장바구니에 담아둔 «나를 뺀» 손님 수.
 *  3명 이상일 때만 뜨므로 «여러 명»은 사실이다. 숫자는 화면에 안 나온다. */
export const HOLDING_MIN_PEOPLE = 3;


/** 판매 순위 등급 — products.sales_rank_pct (0 = 1등, 판매 1개 이상인 상품끼리의 백분위).
 *
 *  [2026-09-20 실제 데이터] 판매가 있는 상품 358개 기준
 *     상위 3%  ≈ 11개 → 「베스트」   (신발 랜덤박스 137 · 버버리 109 · 알로밴딩바지 91 …)
 *     상위 25% ≈ 90개 → 「인기」
 *
 *  사장님 요구: «모든 상품이 잘 팔리는 느낌 들게 설계해야 해 — 광고효과잖아»
 *  숫자를 화면에 안 쓰기로 했기 때문에 기준을 후하게 줄 수 있다.
 *  「인기」는 1개 팔렸든 100개 팔렸든 똑같이 「인기」라 옆 상품과 비교되지 않는다.
 *  → 상위 10%(37개)에서 25%(90개)로 넓혀 자랑거리 없는 상품을 최대한 줄인다.
 *  «한 명만 사도 급상승» 같은 일이 없게 절대 수치가 아니라 순위로 끊는다.
 *  둘은 겹치지 않는다 — 상위 3%는 「베스트」만 붙고 「인기」는 안 붙는다.
 *  💖루루픽은 자동으로 붙이지 않는다(사장님이 «직접 고른 것»이라는 뜻을 지킨다). */
export const TOP_SELLER_RANK_PCT = 0.03;
export const POPULAR_RANK_PCT = 0.25;

export const BADGE_INFO_KEYS = ["free", "overseas", "company", "direct"] as const;

export type BadgeKey = string;

export const MAX_PROMO_BADGES = 2;

const promoRank = (key: BadgeKey) => {
  const i = (BADGE_PROMO_ORDER as readonly string[]).indexOf(key);
  return i < 0 ? Number.MAX_SAFE_INTEGER : i;
};

const isInfo = (key: BadgeKey) => (BADGE_INFO_KEYS as readonly string[]).includes(key);

/**
 * 켜져 있는 배지 key 목록을 받아, 화면에 실제로 그릴 key 집합을 돌려준다.
 * - 정보 배지는 전부 통과
 * - 마케팅 배지는 우선순위 상위 maxPromo 개만
 * 입력 순서는 결과에 영향을 주지 않는다(우선순위 표만 본다).
 */
export function pickVisibleBadges(activeKeys: BadgeKey[], maxPromo: number = MAX_PROMO_BADGES): Set<BadgeKey> {
  const uniq = Array.from(new Set(activeKeys.filter((k) => typeof k === "string" && k.trim() !== "")));
  const info = uniq.filter(isInfo);
  const promo = uniq
    .filter((k) => !isInfo(k))
    .sort((a, b) => promoRank(a) - promoRank(b))
    .slice(0, Math.max(0, maxPromo));
  return new Set([...info, ...promo]);
}
