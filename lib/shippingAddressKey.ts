/** 주소 첫 낱말이 «아는 시도 이름»이면 표준 이름으로 바꾼다. 모르면 그대로.
 *  ⚠ 첫 낱말에만 적용한다. 주소 한가운데의 「경기도로」 같은 길 이름이 망가지면 안 된다. */
function canonicalizeSido(address: string): string {
  const trimmed = address.trim();
  if (!trimmed) return "";
  const at = trimmed.indexOf(" ");
  const head = at < 0 ? trimmed : trimmed.slice(0, at);
  const rest = at < 0 ? "" : trimmed.slice(at + 1);
  const canon = SIDO_CANON[head];
  if (!canon) return trimmed;
  return rest ? `${canon} ${rest}` : canon;
}

/** 비교용으로 다듬은 주소 한 토막.
 *  괄호 안(법정동·단지명 등)은 «같은 주소인데 있다가 없다가» 하므로 뺀다. */
function normalizePart(value: unknown, removeParentheses = false): string {
  let next = String(value ?? "");
  if (removeParentheses) next = next.replace(/\([^)]*\)/g, " ");
  return next
    .replace(/\s+/g, " ")
    .replace(/[-‐-‒–—―]/g, "-")   // 여러 종류의 붙임표를 하나로
    .trim();
}

/**
 * 합배송 «같은 주소» 비교 키. 두 주문의 이 값이 같으면 같은 주소다.
 *
 * ⚠ 우편번호는 «일부러» 안 쓴다.
 *   같은 집인데도 입력 경로(저장된 기본배송지 / 주소검색 / 관리자 편집)에 따라
 *   우편번호가 있다가 없다가 한다. 그러면 키가 어긋나 배송비가 또 붙는다 — 지금 고치는 바로 그 사고다.
 *   도로명주소 + 상세주소면 집이 특정되므로 우편번호는 판정에 보탬이 안 되고 실패 경로만 늘린다.
 *
 * 빈 문자열("")이면 «주소를 모른다»는 뜻 → 부르는 쪽은 합배송을 성립시키면 안 된다.
 */
export function shippingAddressKey(address: unknown, detailAddress: unknown): string {
  const main = canonicalizeSido(normalizePart(address, true));
  const detail = normalizePart(detailAddress);
  const joined = [main, detail].filter(Boolean).join("|");
  // 마지막에 띄어쓰기를 모두 없앤다 — 「대로21길 15」와 「대로21길15」는 같은 곳이다.
  return joined.replace(/\s+/g, "").toLowerCase();
}
