  광주광역시: "광주", 광주시: "광주", 광주: "광주",
  대전광역시: "대전", 대전시: "대전", 대전: "대전",
  울산광역시: "울산", 울산시: "울산", 울산: "울산",
  세종특별자치시: "세종", 세종시: "세종", 세종: "세종",
  경기도: "경기", 경기: "경기",
  강원특별자치도: "강원", 강원도: "강원", 강원: "강원",
  충청북도: "충북", 충북: "충북",
  충청남도: "충남", 충남: "충남",
  전북특별자치도: "전북", 전라북도: "전북", 전북: "전북",
